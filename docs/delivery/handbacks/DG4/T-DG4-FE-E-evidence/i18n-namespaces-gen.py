    keys = [r[0] for r in rows]
    assert len(keys) == len(set(keys)), name
    for lang, idx in (("en", 1), ("ar", 2)):
        with open(f"{ROOT}/{lang}/{name}.json", "w", encoding="utf-8") as f:
            json.dump(nest(rows, idx), f, ensure_ascii=False, indent=2)
            f.write("\n")
