def nest(rows, idx):
    out = {}
    for row in rows:
        key, val = row[0], row[idx]
        parts = key.split(".")
        d = out
        for p in parts[:-1]:
            d = d.setdefault(p, {})
        assert parts[-1] not in d, key
        d[parts[-1]] = val
    return out


