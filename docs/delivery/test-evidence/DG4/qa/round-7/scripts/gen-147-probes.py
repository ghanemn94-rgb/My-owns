#!/usr/bin/env python3
"""qa-verifier DG4 round 7 (F-DG4-147 verification): generate delayed-boot-/me probes of session-end.spec.ts.
Each probe = one version of apps/web/e2e/session-end.spec.ts with ONE inserted line, right after the 'a 403 is not a
session end' test's signIn: page.route forwards the next GET /me (the boot /me of /about) <delay> ms late, forcing the
round-6 trace order (goto returns, re-login, then the boot /me). Versions: 'old' = the round-6 source 1e0dc5d (pre-repair),
'fixed' = this candidate (dab4562). Written to tests/round-7/e2e/zz-qa-r7-147-<ver>-d<delay>.spec.ts (outside the
candidate); copied into a disposable copy's apps/web/e2e/ only to run (relative imports of ./support)."""
import subprocess, sys
repo, out = sys.argv[1], sys.argv[2]
anchor_title = 'test("a 403 is not a session end'
for ver, rev in (("old", "1e0dc5d"), ("fixed", "dab4562")):
    src = subprocess.run(["git", "-C", repo, "show", f"{rev}:apps/web/e2e/session-end.spec.ts"], capture_output=True, text=True, check=True).stdout
    lines = src.split("\n")
    t = next(i for i, l in enumerate(lines) if l.startswith(anchor_title))
    s = next(i for i in range(t, t + 6) if 'await signIn(page, lang, "dev.lead");' in lines[i])
    for delay in (1500, 4000):
        ins = (f'  await page.route("**/api/v1/me", async (route) => {{ if (route.request().method() === "GET") '
               f'await new Promise((r) => setTimeout(r, {delay})); await route.continue(); }}, {{ times: 1 }}); '
               f'// QA-R7 PROBE F-DG4-147: the next GET /me (the boot /me of /about) is forwarded {delay} ms late')
        p = lines[: s + 1] + [ins] + lines[s + 1 :]
        name = f"{out}/zz-qa-r7-147-{ver}-d{delay}.spec.ts"
        open(name, "w").write("// qa-verifier DG4 round 7 probe, generated by round-7/scripts/gen-147-probes.py from " + rev + ":apps/web/e2e/session-end.spec.ts (one line inserted). SYNTHETIC users.\n" + "\n".join(p))
        print(name, "inserted after line", s + 1)
