// code-security-reviewer, DG6 round 5: INSTRUMENTED COPY of the candidate's sensitive-reach-sweep.test.ts (BE-Z5),
// unchanged except that it records the HTTP status of every TL/AUD request and logs a histogram and the operations
// that never answered 200 to the not-admitted readers. Run only in a disposable clone, placed next to the original
// (apps/api/test/integration/access/) so its relative imports resolve; removed afterwards.
// The class sweep for a sensitive benefit's identity and values (T-DG6-BE-Z5; F-DG6-300, F-DG6-280; ADR-0051 §2 and
// its 2026-11-04 amendment; REQ-S10-002 "a sensitive benefit is hidden from a workstream member without the grant";
// M0188), against a scratch database of the run's disposable PostgreSQL seeded with the REAL synthetic demo dataset
// (ADR-0050). Everything is SYNTHETIC: an illustrative example, not Mobily actual performance. Marking a record
// sensitive or granting access is an access decision, never a business approval (G1-G6), and nothing here names or
// touches the engineering gates DG0-DG7.
//
// Ported from the code-security probe zz-cs-r4-sens-sweep.test.ts (round 4) and widened from the 128
// `{transformationId}`-only operations to EVERY GET operation of docs/api/openapi.yaml whose path parameters can be
// filled from the seeded data (each `{xId}` from a row of its table, preferring a row of the sensitive benefit; the
// report definition codes and gate codes expanded), plus the live registers reports, a report snapshot generated by an
// ADMITTED user, the inbox and the executive-decision reads.
//
// One demo benefit gets a unique title and a distinctive planned value (with their audit event); the worker's corrective
// consumer opens its variance case (titled with the benefit's title, as before marking); a TO marks the benefit
// sensitive; an admitted TL records the case red in two review cycles and the worker's blocker escalation creates the
// executive ask and its owner's notification. Then, for every operation:
//   - negative: TL and AUD at the transformation (no grant, not a named party) never receive the title, the
//     "<code> <title>" label or the planned value in any response body (any status);
//   - positive control: a second TL with an explicit grant (admitted) does receive them on the benefit's own reads,
//     the benefit list, the traceability graph, the live register and the stored snapshot (the demo benefit has its
//     upstream links, so the missing-links item is covered by sensitive-reach-derived.test.ts),
//     so the sweep would notice a fix that simply removed the data for everyone.
// The resolved operation count has a floor, so a contract change that silently drops operations from the sweep fails.
