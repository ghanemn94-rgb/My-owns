#!/usr/bin/env bash
# qa-verifier T-DG5-QA-D: mutation checks for the A16 suites. Runs ONLY in a disposable copy of the tree
# ($TMPDIR/mut: apps, packages, tests, e2e, tools, root configs, node_modules, docs/source/playbook.md,
# docs/api/openapi.yaml). Each mutant breaks one asserted behaviour in the COPY, runs the A16 test that asserts it,
# expects it to FAIL, and restores the file. The product tree is never edited.
set -uo pipefail
M="${MUT_DIR:?}"; cd "$M"
export PATH=/opt/nvm/versions/node/v24.21.0/bin:$PATH
run() { # id file sed-expr test-file test-name-filter
  local id="$1" file="$2" expr="$3" tfile="$4" filter="$5"
  cp "$file" "$file.orig"
  sed -i "$expr" "$file"
  if cmp -s "$file" "$file.orig"; then echo "MUTANT $id: sed did not change $file (INVALID)"; mv "$file.orig" "$file"; return; fi
  echo "=== MUTANT $id: $file"; diff "$file.orig" "$file"
  QA_PG_PORT=23750 MTH_PORT_POOL=23751-23769 tests/qa/support/with-pg.sh pnpm vitest run --configLoader runner \
    --project integration "$tfile" -t "$filter" > "$M/mut-$id.log" 2>&1
  local rc=$?
  grep -E "^\s+× |→ |Tests " "$M/mut-$id.log" | head -20
  if [ $rc -ne 0 ]; then echo "MUTANT $id: KILLED (vitest exit $rc)"; else echo "MUTANT $id: SURVIVED (vitest exit 0)"; fi
  mv "$file.orig" "$file"
}
HC=tests/qa/integration/a16-health-check.test.ts
LPT=tests/qa/integration/a16-launch-plan.test.ts
# M1 REQ-S14-002: an assessment with 24 answers is scored (incomplete would show a score and band).
run M1-incomplete packages/shared/src/health/scoring.ts \
  's/if (answers.length < HEALTH_QUESTION_COUNT || applicable === 0)/if (answers.length < HEALTH_QUESTION_COUNT - 1 || applicable === 0)/' \
  $HC ""  # whole file (serial)
# M2 REQ-PB-092: band boundary off by one (a score equal to a band's minimum falls into the band below).
run M2-band-boundary packages/shared/src/health/scoring.ts \
  's/if (min.greaterThan(score)) continue;/if (min.greaterThanOrEqualTo(score)) continue;/' \
  $HC ""
# M3 REQ-PB-091: the 25 question texts not verbatim (trailing whitespace trimmed out / altered).
run M3-question-text apps/api/src/modules/health/questions.ts \
  's/textEn: r.source_label_en,/textEn: r.source_label_en.replace("3-5", "3 to 5"),/' \
  $HC ""
# M4 REQ-PB-086: day d = start + d + 1 (generation one day late).
run M4-plan-dates apps/api/src/modules/launch/plan.ts \
  's/return new Date(Date.UTC(y, m - 1, d) + n \* DAY_MS)/return new Date(Date.UTC(y, m - 1, d) + (n + 1) * DAY_MS)/' \
  $LPT ""  # whole file (serial)
# M5 REQ-S14-004: re-dating also moves started tasks (only cancelled ones kept).
run M5-redate-scope apps/api/src/modules/launch/plan.ts \
  '367s/.where("status", "=", "not_started")/.where("status", "in", ["not_started", "in_progress"])/' \
  $LPT ""  # whole file: the launch-plan tests are serial (the plan is generated by an earlier test)
# M6 REQ-PB-087: the Day-90 test reports complete with five of six answers.
run M6-day90-complete apps/api/src/modules/launch/day-ninety.ts \
  's/complete: test.answered_count === questions.length,/complete: test.answered_count >= questions.length - 1,/' \
  $LPT ""  # whole file (serial)
# M7 REQ-S12-004: the worker's starter-1 generator dates tasks one day late.
run M7-starter-dates apps/worker/src/automation/ports/launch-plan-generator.ts \
  's/start_date: addCalendarDays(request.startDate, item.start_day),/start_date: addCalendarDays(request.startDate, item.start_day + 1),/; s/due_date: addCalendarDays(request.startDate, item.due_day),/due_date: addCalendarDays(request.startDate, item.due_day + 1),/' \
  $LPT ""  # whole file (serial)
# M8 REQ-PB-091: the API's three-action check removed (the database guard is the backstop).
run M8-three-actions-api apps/api/src/modules/health/assessments.ts \
  's/if (actions.n !== HEALTH_CHECK_ACTIONS_REQUIRED) throw ACTIONS_REQUIRED();/void ACTIONS_REQUIRED;/' \
  $HC ""
