#!/usr/bin/env bash
# qa-verifier T-DG5-QA-E2: applies mutation $2 to the disposable copy $1 (a git clone of the integrated HEAD 6f8ce12 in
# $TMPDIR, with the tree's built dist/ copied in and node_modules symlinked; NEVER the working tree), runs the suite that
# must kill it, writes the log and the diff, then restores the mutated file from its pristine copy.
#   mutate.sh <copy> <id> <log>
set -u
M="$1"; ID="$2"; LOG="$3"
cd "$M"
export PATH=/opt/nvm/versions/node/v24.21.0/bin:$PATH
mut() { # file python-old python-new
  cp "$1" "$1.pristine"
  python3 - "$1" "$2" "$3" <<'P'
import sys
p, a, b = sys.argv[1:]
s = open(p, encoding="utf-8").read()
assert a in s, f"mutation anchor not found in {p}"
open(p, "w", encoding="utf-8").write(s.replace(a, b, 1))
P
  diff -u "$1.pristine" "$1" > "$LOG.diff"
}
restore() { mv "$1.pristine" "$1"; }
integ() { QA_PG_PORT=23630 MTH_PORT_POOL=23631-23639 timeout 900 tests/qa/support/with-pg.sh pnpm vitest run --configLoader runner --project integration tests/qa/integration/a02-a21-complete-lifecycle.test.ts > "$LOG" 2>&1; echo "$ID vitest exit=$?"; }
demo() { E2E_PG_PORT=23640 E2E_API_PORT=23641 MTH_PORT_POOL=23642-23649 PLAYWRIGHT_BROWSERS_PATH=/opt/pw-browsers timeout 1200 e2e/support/with-demo-stack.sh npx playwright test "$@" --project chromium-en --workers=1 --reporter=list > "$LOG" 2>&1; echo "$ID playwright exit=$?"; }
WEB=$(ls apps/web/dist/assets/index-*.js | head -1)
case "$ID" in
  M1) F=packages/db/migrations/0095_p5_procedures_v2_baseline_assignee.sql
      mut $F "AND s.step_key = 'record_baseline' THEN 'TL'" "AND s.step_key = 'record_baseline' THEN 'BO'"; integ; restore $F ;;
  M2) F=apps/api/src/modules/procedures/steps.ts
      mut $F "  if (!mine) throw refusal(\"procedure_step.not_assignee\")" "  if (!mine && false) throw refusal(\"procedure_step.not_assignee\")"; integ; restore $F ;;
  M3) F=apps/api/dist/modules/admin/walkthrough.js
      mut $F 'kpi_actual_submitted: (t) => sql `SELECT EXISTS' 'kpi_actual_submitted: (t) => sql `SELECT false AND EXISTS'
      demo e2e/a02-demo-users-walkthrough.spec.ts; restore $F ;;
  M4) mut $WEB 'banner:"Illustrative example — synthetic. Not Mobily actual performance."' 'banner:"Example data."'
      demo e2e/a02-demo-labels.spec.ts --grep "banner on every visited screen"; restore $WEB ;;
  M5) mut $WEB 'approvalLabel:"Synthetic demonstration - approves nothing real"' 'approvalLabel:""'
      demo e2e/a02-demo-labels.spec.ts --grep "banner on every visited screen"; restore $WEB ;;
  M6) F=packages/reporting/dist/labels.js
      mut $F '"export.illustrative": "Illustrative example — synthetic",' '"export.illustrative": "",'
      demo e2e/a02-demo-labels.spec.ts --grep "an export generated by the worker"; restore $F ;;
esac
