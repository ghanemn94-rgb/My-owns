/** Why a delivery was refused (the redacted log line and the counter; never sent to the caller). */
export type WebhookRejection =
  | "endpoint_unknown"
  | "endpoint_disabled"
  | "connector_disabled"
  | "header_missing"
  | "header_malformed"
  | "timestamp_outside_window"
  | "secret_unresolvable"
  | "signature_mismatch"
  | "service_identity_out_of_scope";

const rejections = new Map<WebhookRejection, number>();

/** The rejection counter of this process, by reason (operators read it through the log; tests read it here). */
export function webhookRejectionCounts(): ReadonlyMap<WebhookRejection, number> {
  return new Map(rejections);
}

class Rejected extends Error {
  readonly reason: WebhookRejection;
  readonly endpointId: string | null;
  constructor(reason: WebhookRejection, endpointId: string | null = null) {
    super(reason);
    this.reason = reason;
    this.endpointId = endpointId;
  }
}

/** Logs the refusal (redacted: the reason and the endpoint id only) and returns the one 401. */
function reject(log: FastifyBaseLogger, reason: WebhookRejection, endpointId: string | null): HttpProblem {
  rejections.set(reason, (rejections.get(reason) ?? 0) + 1);
  log.warn({ webhookRejection: { reason, endpointId } }, "webhook delivery rejected");
  return webhookRefusals.unauthenticated();
}

/** HMAC-SHA256 hex of "<timestamp>.<deliveryId>.<raw body>" with the secret's UTF-8 bytes. */
export function webhookSignature(secret: string, timestamp: string, deliveryId: string, body: Uint8Array): string {
  return createHmac("sha256", secret).update(`${timestamp}.${deliveryId}.`).update(body).digest("hex");
}

function sameSignature(expectedHex: string, presentedHex: string): boolean {
  const a = Buffer.from(expectedHex, "hex");
  const b = Buffer.from(presentedHex, "hex");
  return a.length === b.length && timingSafeEqual(a, b);
}

/** One SecretRef resolved now (outside any transaction); null when it does not resolve. */
async function resolveRef(ref: { provider: string; name: string } | null): Promise<string | null> {
  if (ref === null) return null;
  try {
    const resolved = await resolveCredentials({ signing: ref });
    return resolved.get("signing")?.reveal() ?? null;
  } catch {
    return null;
  }
}

