function refOf(stored: unknown): { provider: string; name: string } | null {
  if (stored === null || typeof stored !== "object") return null;
  const v = stored as { provider?: unknown; name?: unknown };
  return typeof v.provider === "string" && typeof v.name === "string" ? { provider: v.provider, name: v.name } : null;
}

/** The newest accepted receipt per endpoint (null: none yet). */
export async function lastReceipts(db: DbOrTx, endpointIds: readonly string[]): Promise<Map<string, Date>> {
  if (endpointIds.length === 0) return new Map();
  const rows = await db
    .selectFrom("webhook_receipt")
    .select(["webhook_endpoint_id", (eb) => eb.fn.max("received_at").as("last")])
    .where("webhook_endpoint_id", "in", [...endpointIds])
    .groupBy("webhook_endpoint_id")
    .execute();
  return new Map(rows.map((r) => [r.webhook_endpoint_id, r.last as Date]));
}

