// Signed webhooks to a staged import (ADR-0056 §7-§9; REQ-S17-003; p6-work-split §B/A.6; T-DG6-BE-N). The routes are
// in routes.ts (webhook block).
//
// Endpoint administration (ADR-0056 §7 "Admin routes"; 0107, permissions matrix §26):
//   reads (list, get) are `connector.read`, exactly as reading the owning connector (an unreadable connector or an
//   endpoint of one is 404); create, rotate and disable are `webhook.configure` (ADM_TECH) at the connector's
//   organization (403 for a reader without it, AUD included). The signing secret is a SecretRef `{provider, name}` that
//   IT provisions in the secret provider and gives to the sender: the application never generates, shows, stores, logs
//   or audits a secret value (422 connector.secret_value_refused for anything but a reference). The endpoint key (the
//   path segment) is generated by the server: 32 random bytes, base64url. Every change re-checks authorization at
//   commit time on reloaded grants, after the row lock, requires If-Match (except the create) and writes one audit
//   event with its prior and new version.
//
// receiveWebhook (`POST /api/v1/webhooks/{endpointKey}`; no session, CSRF-exempt, authenticated by the signature only):
//   BEFORE any transaction (no remote I/O inside one, p6-work-split §2 rule 4):
//     1. the endpoint by key; its connector; the three headers; the timestamp window; the SecretProvider resolves the
//        current reference (and the previous one while `now <= previous_valid_until`); HMAC-SHA256 over
//        "<timestamp>.<deliveryId>.<raw body bytes>" compared in constant time (crypto.timingSafeEqual). Every failure
//        is the SAME 401 webhook.unauthenticated (one code, one text): the reason goes only to a redacted log line
//        (never the signature, a secret, a header value or the body) and to the rejection counter. No row is stored.
//     2. the body is decoded as strict UTF-8 and parsed with the platform's JSON parser only after the signature
//        matched (an unsigned body is never parsed); 400 webhook.payload_invalid when it is not the documented shape.
//     3. a replay is answered from the stored receipt (same delivery id and body: 200, nothing new; another body: 409
//        webhook.delivery_id_reused) before any validation work.
//     4. the items are mapped by the connector's field mappings (source key -> template column; no mappings: the
//        template's own column keys) and validated read-only by BE-M's engine (`prepareImport`); a JSON number or any
//        other non-string value is the row reason import.row.value_not_decimal, never coerced.
//   ONE transaction under the webhookReceipt advisory lock (key "<endpointId>:<deliveryId>") and the connectorRun lock
//     (key connector id; one active run per connector): the replay check again (the unique key is the backstop); the
//     receipt; an integration_run (`trigger_kind = 'webhook'`, key `webhook:<receipt id>`, the connector's service
//     identity) queued -> running -> succeeded with its counts; the staged import_batch (`source_kind = 'webhook'`)
//     with its rows; audit actor `service` for every record. 202 with the counts.
//   AFTER that transaction, for `commit_mode = 'auto'`: ADR-0056 §6's commit on behalf of `commit_on_behalf_of`,
//     re-authorized at commit on that user's current grants. A refusal leaves the batch `staged` and writes the audit
//     event `import_batch.auto_commit_refused`; a KDS commits by hand in Strategy and KPIs > Imports.
//
// Nothing here is "live": no external sender is exercised (the suites sign with a test secret). Nothing here reads or
// writes DG0-DG7 or grants a business approval; an auto commit submits KPI actuals through DG4, which decides each.
