/** One endpoint the principal may read (through its connector, `connector.read`); 404 otherwise. */
export async function visibleEndpoint(db: DbOrTx, principal: Principal, id: string): Promise<WebhookEndpointRow> {
  const row = await db.selectFrom("webhook_endpoint").selectAll().where("id", "=", id).executeTakeFirst();
  if (!row) {
    principal.tracker.decisions += 1;
    throw problems.notFound();
  }
  await visibleConnector(db, principal, row.connector_id);
  return row;
}

/** The configure gate of a change: the read gate (404), then `webhook.configure` at the organization (403). */
export async function requireWebhookConfigure(db: DbOrTx, principal: Principal, organizationId: string): Promise<void> {
  if (!(await holdsAtOrganization(db, principal, WEBHOOK_CONFIGURE, organizationId))) throw problems.forbidden();
}

/** Commit-time re-check on the reloaded grants (a right lost meanwhile is 403, F-DG2-440). */
async function recheckConfigure(tx: Tx, request: FastifyRequest, connectorId: string): Promise<string> {
  const fresh = await refreshPrincipal(tx, request);
  try {
    const connector = await visibleConnector(tx, fresh, connectorId);
    await requireWebhookConfigure(tx, fresh, connector.organization_id);
  } catch (err) {
    if (err instanceof HttpProblem && err.status === 404)
      throw problems.forbidden("Your access to this record changed while the request was in progress.");
    throw commitTimeDenial(err);
  }
  return fresh.userId!;
}

