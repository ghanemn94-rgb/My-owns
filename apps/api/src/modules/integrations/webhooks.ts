/** The three signature headers (literal keys: a string value, else undefined). */
function signatureHeaders(headers: ReceiveInput["headers"]) {
  const text = (v: string | string[] | undefined) => (typeof v === "string" ? v : undefined);
  return {
    timestamp: text(headers["x-mth-webhook-timestamp"]),
    deliveryId: text(headers["x-mth-webhook-delivery"]),
    signature: text(headers["x-mth-webhook-signature"]),
  };
}

/** Step 1: every authentication check; throws Rejected with the reason. */
async function verify(db: Db, input: ReceiveInput): Promise<Verified> {
  if (!ENDPOINT_KEY.test(input.endpointKey)) throw new Rejected("endpoint_unknown");
  const endpoint = await db
    .selectFrom("webhook_endpoint")
    .selectAll()
    .where("endpoint_key", "=", input.endpointKey)
    .executeTakeFirst();
  if (!endpoint) throw new Rejected("endpoint_unknown");
  const fail = (reason: WebhookRejection): never => {
    throw new Rejected(reason, endpoint.id);
  };
  if (endpoint.status !== "active") fail("endpoint_disabled");
  const connector = (await findConnector(db, endpoint.connector_id))!;
  if (connector.status !== "enabled") fail("connector_disabled");
  const { timestamp: ts, deliveryId, signature } = signatureHeaders(input.headers);
  if (ts === undefined || deliveryId === undefined || signature === undefined) fail("header_missing");
  const presented = SIGNATURE.exec(signature!)?.[1];
  if (!TIMESTAMP.test(ts!) || !DELIVERY_ID.test(deliveryId!) || presented === undefined) fail("header_malformed");
  const nowMs = (input.now ?? Date.now)();
  const signedAtMs = Number(ts) * 1000;
  if (Math.abs(nowMs - signedAtMs) > endpoint.tolerance_seconds * 1000) fail("timestamp_outside_window");
  // The secrets are resolved here, before any transaction (ADR-0052 §5); the values never leave this function.
  const current = await resolveRef(refOf(endpoint.signing_secret_ref));
  const previousValid = endpoint.previous_valid_until !== null && nowMs <= endpoint.previous_valid_until.getTime();
  const previous = previousValid ? await resolveRef(refOf(endpoint.previous_secret_ref)) : null;
  if (current === null && previous === null) fail("secret_unresolvable");
  let slot: "current" | "previous" | null = null;
  if (current !== null && sameSignature(webhookSignature(current, ts!, deliveryId!, input.body), presented!))
    slot = "current";
  else if (previous !== null && sameSignature(webhookSignature(previous, ts!, deliveryId!, input.body), presented!))
    slot = "previous";
  if (slot === null) fail("signature_mismatch");
  return {
    endpoint,
    connector,
    deliveryId: deliveryId!,
    signedAt: new Date(signedAtMs),
    receivedAt: new Date(nowMs),
    slot: slot!,
    bodySha256: createHash("sha256").update(input.body).digest("hex"),
  };
}

/** Step 2: the body, parsed only after the signature matched. */
async function parseDelivery(input: ReceiveInput): Promise<z.infer<typeof webhookDelivery>> {
  const text = decodeUtf8Body(input.body);
  if (text === null || text.charCodeAt(0) === 0xfeff) throw webhookRefusals.payloadInvalid();
  let value: unknown;
  try {
    value = await input.parseJson(text);
  } catch {
    throw webhookRefusals.payloadInvalid();
  }
  const parsed = webhookDelivery.safeParse(value);
  if (!parsed.success) {
    const path = parsed.error.issues[0]?.path ?? [];
    throw webhookRefusals.payloadInvalid(path.length === 0 ? "" : `/${path.map(String).join("/")}`);
  }
  return parsed.data;
}

/** The connector's field mappings applied to the items, keeping every value as sent (a number stays non-text). */
export function mapItems(
  items: readonly Readonly<Record<string, unknown>>[],
  mappings: readonly FieldMapping[],
): Record<string, unknown>[] {
  if (mappings.length === 0) return items.map((i) => ({ ...i }));
  return items.map((item) => {
    const cells = new Map(Object.entries(item));
    return Object.fromEntries(mappings.map((m) => [m.target, cells.has(m.source) ? cells.get(m.source) : null]));
  });
}

/** The receipt already stored for (endpoint, delivery id), as a replay result; 409 for another body. */
async function replayOf(db: DbOrTx, v: Verified): Promise<WebhookReceiptResult | null> {
  const r = await db
    .selectFrom("webhook_receipt as r")
    .innerJoin("import_batch as b", "b.webhook_receipt_id", "r.id")
    .select([
      "r.id as receipt_id",
      "r.body_sha256",
      "b.id as batch_id",
      "b.rows_total",
      "b.rows_valid",
      "b.rows_invalid",
      "b.rows_duplicate",
    ])
    .where("r.webhook_endpoint_id", "=", v.endpoint.id)
    .where("r.delivery_id", "=", v.deliveryId)
    .executeTakeFirst();
  if (!r) return null;
  if (r.body_sha256 !== v.bodySha256) throw webhookRefusals.deliveryIdReused();
  return {
    receiptId: r.receipt_id,
    importBatchId: r.batch_id,
    replay: true,
    rowsTotal: r.rows_total ?? 0,
    rowsValid: r.rows_valid ?? 0,
    rowsInvalid: r.rows_invalid ?? 0,
    rowsDuplicate: r.rows_duplicate ?? 0,
  };
}

/** The template a payload names, when it is registered for the connector's target kind. */
function templateFor(targets: ImportTargetRegistry, kind: string, version: string): string | null {
  const t = targets.get(version);
  return t !== undefined && t.kind === kind ? t.templateVersion : null;
}

/**
 * receiveWebhook (ADR-0056 §7). Returns the result and whether it is a replay (200) or new (202). Every
 * authentication failure throws the one 401; the auto commit (if configured) runs after the staging transaction.
 */
export async function receiveWebhook(db: Db, input: ReceiveInput): Promise<WebhookReceiptResult> {
  let v: Verified;
  try {
    v = await verify(db, input);
  } catch (err) {
    if (!(err instanceof Rejected)) throw err;
    throw reject(input.log, err.reason, err.endpointId);
  }
  const delivery = await parseDelivery(input);
  const early = await replayOf(db, v);
  if (early !== null) return early;

  const config = await currentConfig(db, v.connector);
  const identity = await db
    .selectFrom("service_identity")
    .select(["id", "granted_permission_codes"])
    .where("connector_id", "=", v.connector.id)
    .where("subject_kind", "=", "connector")
    .executeTakeFirstOrThrow();
  // The connector's service identity reads the target transformation (ADR-0053 §1); a narrowed grant stops staging.
  if (!identity.granted_permission_codes.includes("transformation.read"))
    throw reject(input.log, "service_identity_out_of_scope", v.endpoint.id);
  const targets = input.targets ?? importTargetRegistry();
  const template = templateFor(targets, v.connector.target_kind, delivery.templateVersion);
  if (template === null || config.target_transformation_id === null)
    throw webhookRefusals.payloadInvalid("/templateVersion");
  const auto = config.commit_mode === "auto" && config.commit_on_behalf_of !== null;
  let prepared: PreparedImport;
  try {
    prepared = await prepareImport(
      db,
      {
        templateVersion: template,
        transformationId: config.target_transformation_id,
        actorUserId: auto ? config.commit_on_behalf_of : null,
        table: tableFromJsonItems(mapItems(delivery.items, config.field_mappings as FieldMapping[])),
      },
      targets,
    );
  } catch (err) {
    // The item keys do not fit the template (import.header_mismatch) or the rows exceed a limit: the body is not in the
    // documented format (the contract declares 400 for it).
    if (err instanceof HttpProblem && err.status === 422)
      throw webhookRefusals.payloadInvalid("/items", { code: err.code, message: err.detail ?? err.title });
    throw err;
  }

  const ctx: AuditContext = { actorUserId: null, actorType: "service", requestId: input.requestId };
  const staged = await db.transaction().execute(async (tx) => {
    await sql`SELECT pg_advisory_xact_lock(${ADVISORY_LOCK_CLASSES.webhookReceipt}::int4, hashtext(${`${v.endpoint.id}:${v.deliveryId}`}::text))`.execute(
      tx,
    );
    const replay = await replayOf(tx, v);
    if (replay !== null) return { replay, batch: null };
    await sql`SELECT pg_advisory_xact_lock(${ADVISORY_LOCK_CLASSES.connectorRun}::int4, hashtext(${v.connector.id}::text))`.execute(
      tx,
    );
    // The endpoint and connector as they are now (a disable meanwhile refuses the delivery like any other 401).
    const endpoint = await tx
      .selectFrom("webhook_endpoint")
      .select(["status"])
      .where("id", "=", v.endpoint.id)
      .forShare()
      .executeTakeFirstOrThrow();
    if (endpoint.status !== "active") throw reject(input.log, "endpoint_disabled", v.endpoint.id);
    const connector = (await findConnector(tx, v.connector.id))!;
    if (connector.status !== "enabled") throw reject(input.log, "connector_disabled", v.endpoint.id);

    const receiptId = uuidv7();
    await tx
      .insertInto("webhook_receipt")
      .values({
        id: receiptId,
        organization_id: v.endpoint.organization_id,
        webhook_endpoint_id: v.endpoint.id,
        delivery_id: v.deliveryId,
        signed_at: v.signedAt,
        received_at: v.receivedAt,
        secret_slot: v.slot,
        body_sha256: v.bodySha256,
        body_bytes: input.body.byteLength,
        item_count: delivery.items.length,
      })
      .execute();
    await audit(tx, ctx, {
      action: "webhook_receipt.accepted",
      recordType: "webhook_receipt",
      recordId: receiptId,
      organizationId: v.endpoint.organization_id,
      transformationId: config.target_transformation_id,
      newVersion: 1,
      changes: {
        webhook_endpoint_id: { from: null, to: v.endpoint.id },
        delivery_id: { from: null, to: v.deliveryId },
        // "secret" may not name an audit field (packages/db audit.ts): the slot is recorded as key_slot.
        key_slot: { from: null, to: v.slot },
        item_count: { from: null, to: delivery.items.length },
      },
    });
    const run = await startWebhookRun(tx, ctx, connector, identity.id, receiptId);
    const batch = await stageImportInTx(tx, prepared, {
      source: {
        kind: "webhook",
        connectorId: connector.id,
        webhookReceiptId: receiptId,
        commitMode: auto ? "auto" : "manual",
        onBehalfOfUserId: auto ? config.commit_on_behalf_of : null,
      },
      createdBy: null,
      audit: ctx,
    });
    await finishWebhookRun(tx, ctx, run, batch, delivery.items.length);
    return {
      replay: null,
      batch,
      result: {
        receiptId,
        importBatchId: batch.id,
        replay: false,
        rowsTotal: batch.rows_total ?? 0,
        rowsValid: batch.rows_valid ?? 0,
        rowsInvalid: batch.rows_invalid ?? 0,
        rowsDuplicate: batch.rows_duplicate ?? 0,
      } satisfies WebhookReceiptResult,
    };
  });
  if (staged.replay !== null) return staged.replay;
  if (auto && (staged.batch.rows_valid ?? 0) > 0)
    await autoCommit(db, staged.batch, config.commit_on_behalf_of!, input.requestId, targets, input.log);
  return staged.result;
}

type RunRow = { id: string; version: number; organization_id: string };

/** The delivery's integration run: queued (v1) -> running (v2), as the connector's service identity. */
async function startWebhookRun(
  tx: Tx,
  ctx: AuditContext,
  connector: ConnectorRow,
  serviceIdentityId: string,
  receiptId: string,
): Promise<RunRow & { started_at: Date }> {
  const id = uuidv7();
  await tx
    .insertInto("integration_run")
    .values({
      id,
      organization_id: connector.organization_id,
      connector_id: connector.id,
      config_version_no: connector.config_version_no,
      trigger_kind: "webhook",
      attempt_no: 1,
      retry_of_run_id: null,
      idempotency_key: `webhook:${receiptId}`,
      requested_by: null,
      service_identity_id: serviceIdentityId,
      queued_at: sql<Date>`now()`,
      created_by: null,
      updated_by: null,
    })
    .execute();
  await audit(tx, ctx, {
    action: "integration_run.queued",
    recordType: "integration_run",
    recordId: id,
    organizationId: connector.organization_id,
    newVersion: 1,
    changes: {
      connector_id: { from: null, to: connector.id },
      trigger_kind: { from: null, to: "webhook" },
      attempt_no: { from: null, to: 1 },
      config_version_no: { from: null, to: connector.config_version_no },
      status: { from: null, to: "queued" },
    },
  });
  const running = await tx
    .updateTable("integration_run")
    .set({ status: "running", started_at: sql<Date>`now()`, version: 2, updated_at: sql<Date>`now()` })
    .where("id", "=", id)
    .where("version", "=", 1)
    .returning(["id", "version", "organization_id", "started_at"])
    .executeTakeFirstOrThrow();
  await audit(tx, ctx, {
    action: "integration_run.started",
    recordType: "integration_run",
    recordId: id,
    organizationId: connector.organization_id,
    priorVersion: 1,
    newVersion: 2,
    changes: { status: { from: "queued", to: "running" } },
  });
  return { ...running, started_at: running.started_at! };
}

/** The run `succeeded` with the batch's counts (reconciliation: not applicable to a pushed delivery). */
async function finishWebhookRun(
  tx: Tx,
  ctx: AuditContext,
  run: RunRow & { started_at: Date },
  batch: ImportBatchRow,
  itemCount: number,
): Promise<void> {
  const finished = await tx
    .updateTable("integration_run")
    .set({
      status: "succeeded",
      finished_at: sql<Date>`greatest(now(), ${run.started_at}::timestamptz)`,
      rows_read: itemCount,
      rows_staged: batch.rows_total ?? 0,
      rows_rejected: batch.rows_invalid ?? 0,
      rows_duplicate: batch.rows_duplicate ?? 0,
      error_count: batch.rows_invalid ?? 0,
      reconciliation_status: "not_applicable",
      import_batch_id: batch.id,
      version: run.version + 1,
      updated_at: sql<Date>`now()`,
    })
    .where("id", "=", run.id)
    .where("version", "=", run.version)
    .returning(["version"])
    .executeTakeFirstOrThrow();
  await audit(tx, ctx, {
    action: "integration_run.succeeded",
    recordType: "integration_run",
    recordId: run.id,
    organizationId: run.organization_id,
    priorVersion: run.version,
    newVersion: finished.version,
    changes: {
      status: { from: "running", to: "succeeded" },
      rows_read: { from: null, to: itemCount },
      rows_staged: { from: null, to: batch.rows_total ?? 0 },
      rows_rejected: { from: null, to: batch.rows_invalid ?? 0 },
      rows_duplicate: { from: null, to: batch.rows_duplicate ?? 0 },
      import_batch_id: { from: null, to: batch.id },
    },
  });
}

/** A user's principal built from the current grants (the auto commit's on-behalf-of user; no request). */
async function principalOfUser(db: DbOrTx, userId: string): Promise<Principal | null> {
  const user = await db
    .selectFrom("app_user")
    .select(["id", "organization_id", "status"])
    .where("id", "=", userId)
    .executeTakeFirst();
  if (!user || user.status !== "active") return null;
  return {
    kind: "user",
    userId,
    organizationId: user.organization_id,
    grants: await loadGrants(db, userId),
    tracker: { decisions: 0 },
  };
}

/**
 * The auto commit of ADR-0056 §7 step 3, after the staging transaction: ADR-0056 §6 on behalf of the configured user,
 * re-authorized inside the commit transaction on that user's current grants. A refusal (403, revalidation, a state
 * change) leaves the batch `staged` and is recorded as `import_batch.auto_commit_refused` with its problem code.
 */
async function autoCommit(
  db: Db,
  batch: ImportBatchRow,
  userId: string,
  requestId: string,
  targets: ImportTargetRegistry,
  log: FastifyBaseLogger,
): Promise<void> {
  const ctx: AuditContext = { actorUserId: null, actorType: "service", onBehalfOfUserId: userId, requestId };
  try {
    await db.transaction().execute((tx) =>
      commitBatchInTx(
        tx,
        {
          transformationId: batch.transformation_id,
          batchId: batch.id,
          expectedVersion: batch.version,
          note: null,
          userId,
          committedBy: null,
          audit: ctx,
          recheck: async (t, permissions) => {
            const principal = await principalOfUser(t, userId);
            if (principal === null) throw problems.forbidden();
            await requireImportAction(t, principal, batch.transformation_id, permissions);
          },
        },
        targets,
      ),
    );
  } catch (err) {
    if (!(err instanceof HttpProblem)) throw err;
    log.info({ webhookAutoCommit: { batchId: batch.id, code: err.code ?? null } }, "webhook auto commit refused");
    await db.transaction().execute(async (tx) => {
      await audit(tx, ctx, {
        action: "import_batch.auto_commit_refused",
        recordType: "import_batch",
        recordId: batch.id,
        organizationId: batch.organization_id,
        transformationId: batch.transformation_id,
        // No version step: the refusal changes nothing on the batch (it stays `staged` at this version).
        reason: err.detail ?? null,
        changes: {
          refusal_code: { from: null, to: err.code ?? `http_${err.status}` },
          batch_version: { from: batch.version, to: batch.version },
        },
      });
    });
  }
}
