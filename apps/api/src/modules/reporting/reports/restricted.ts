// Sensitive records in report documents (T-DG6-BE-Z5; F-DG6-300; ADR-0051 §2 and its 2026-11-04 amendment; D-195 Q3;
// REQ-S10-002 "a sensitive benefit is hidden from a workstream member without the grant"; M0188).
//
// The assemblers take no principal: a document is assembled once, identically for every reader, and a stored snapshot
// keeps that content unchanged (its `contentSha256` is the hash of what was stored, ADR-0046 §2). The sensitivity rule
// is applied when a document LEAVES the API, per reader, for the live report and for every snapshot response:
//   - the subject: a document whose subject is a record the reader is not admitted to (a sensitive business case) is
//     answered 404 `not_found`, as the record's own GET (existence not disclosed);
//   - table rows and list items: a row or item whose record is restricted for the reader (a sensitive benefit,
//     business case or evidence item, or a child that carries its values: SENSITIVE_CHILD_SOURCES, e.g. a measurement,
//     a corrective case, a business-case line) is OMITTED, with no placeholder and no count;
//   - section sources: the restricted references are removed (they name the record);
//   - table totals and metrics are unchanged: an aggregate that includes a restricted value is computed exactly as in
//     DG4/DG5 for every reader and never shows the individual value (D-195 Q3);
//   - T-DG6-BE-Z7B (F-DG6-340; ADR-0051 §2 "Totals and rollups"): a section that references a marked-sensitive record
//     (a row, an item or a source, or, T-DG6-BE-Z9, a record its aggregate figures include: below) carries `includesRestrictedRecords`: `true` when the reader is not admitted to at
//     least one of them (its totals then include a value whose row is not shown, and the screen labels it "Includes
//     restricted records" / "يشمل سجلات مقيدة"), `false` when the reader is admitted to all. It is a READ-TIME member:
//     the assemblers never set it, so stored content and its `contentSha256` are unchanged, and a document that
//     references no sensitive record is returned unchanged byte for byte (the same object).
//   - T-DG6-BE-Z9 (F-DG6-400; ADR-0051 §2 "Totals and rollups"; D-195 Q3): a section whose figures are AGGREGATES of
//     records it names nowhere (the executive pack's `metrics_<subject>` and the executive dashboard's `area_value`
//     include the dashboard facts' benefits and business cases; the executive dashboard's `items_portfolio` rows include
//     the benefits allocated to each initiative; the gate pack's criteria count unverified evidence items) is decided
//     from those records too (`AggregateRef`, assembler.ts): the flag is true when the reader is not admitted to at
//     least one sensitive record the aggregate includes, false when admitted to all, absent when none is sensitive. A
//     live report takes them from its assembly; a stored snapshot from `report_snapshot_aggregate` (migration 0126),
//     or, for a snapshot stored before 0126 (`aggregates_recorded` false), conservatively from every record of those
//     types marked sensitive in its transformation (`legacyAggregates`). They are never shown and never omit anything.
// A stored snapshot generated by an admitted user therefore shows its restricted rows to admitted readers only. The
// export of such a snapshot stays refused for a reader who is not admitted (D-199, exports/jobs.ts).
// Read only. Nothing here is a business approval (G1-G6) and nothing touches DG0-DG7.
import type { DbOrTx } from "@mth/db";
import type { ReportDocument, ReportRecordRef, ReportSection } from "@mth/shared/schemas";
import type { AggregateRef } from "./assembler.ts";
import {
  reachKey,
  recordRefSensitivity,
  restrictedRecordRefs,
  type Principal,
  type ReachRef,
} from "../../access/index.ts";
import { problems } from "../../platform/index.ts";

/** The record a document's subject names, when the subject type can be sensitive (else null). */
function subjectRef(doc: ReportDocument): ReachRef | null {
  return doc.subject.type === "business_case" ? { recordType: "business_case", recordId: doc.subject.id } : null;
}

/** Every record reference one section discloses: its sources, table rows and list items. */
function sectionRefs(s: ReportSection): ReachRef[] {
  const refs: ReachRef[] = s.sources.map((src) => ({ recordType: src.recordType, recordId: src.recordId }));
  if (s.kind === "table") for (const r of s.rows) refs.push({ recordType: r.recordType, recordId: r.recordId });
  if (s.kind === "list")
    for (const i of s.items)
      if (i.record !== null) refs.push({ recordType: i.record.recordType, recordId: i.record.recordId });
  return refs;
}

/** Every record reference a document discloses: its subject, table rows, list items and section sources. */
function refsOf(doc: ReportDocument): ReachRef[] {
  const refs: ReachRef[] = [];
  const subject = subjectRef(doc);
  if (subject !== null) refs.push(subject);
  for (const s of doc.sections) refs.push(...sectionRefs(s));
  return refs;
}

/**
 * The document as this reader may see it (see the file header). `aggregates` are the records the sections' aggregate
 * figures include beyond their own references (they only decide the flag). Returns the SAME object when nothing in it
 * is sensitive (every DG5 response is unchanged byte for byte until a record is marked sensitive).
 */
export async function documentForReader(
  db: DbOrTx,
  principal: Principal,
  doc: ReportDocument,
  aggregates: readonly AggregateRef[] = [],
): Promise<ReportDocument> {
  const included = new Map<string, ReachRef[]>();
  for (const a of aggregates) {
    const list = included.get(a.sectionKey) ?? [];
    list.push({ recordType: a.recordType, recordId: a.recordId });
    included.set(a.sectionKey, list);
  }
  const { sensitive, restricted } = await recordRefSensitivity(db, principal, [
    ...refsOf(doc),
    ...[...included.values()].flat(),
  ]);
  if (sensitive.size === 0) return doc;
  const subject = subjectRef(doc);
  if (subject !== null && restricted.has(reachKey(subject))) throw problems.notFound();
  const hidden = (r: { recordType: string; recordId: string }) => restricted.has(reachKey(r));
  const sources = (list: readonly ReportRecordRef[]) => list.filter((src) => !hidden(src));
  const sections = doc.sections.map((s): ReportSection => {
    // Decided on the section as assembled (before anything is omitted): the totals and metrics include those values,
    // and those of the records its aggregate figures include (T-DG6-BE-Z9).
    const keys = [...sectionRefs(s), ...(included.get(s.key) ?? [])].map(reachKey);
    const flag = keys.some((k) => sensitive.has(k))
      ? { includesRestrictedRecords: keys.some((k) => restricted.has(k)) }
      : {};
    switch (s.kind) {
      case "table":
        return { ...s, sources: sources(s.sources), rows: s.rows.filter((r) => !hidden(r)), ...flag };
      case "list":
        return {
          ...s,
          sources: sources(s.sources),
          items: s.items.filter((i) => i.record === null || !hidden(i.record)),
          ...flag,
        };
      default:
        return { ...s, sources: sources(s.sources), ...flag };
    }
  });
  return { ...doc, sections };
}

/**
 * The aggregate sections of a snapshot stored before migration 0126 (T-DG6-BE-Z9), whose included records were not
 * recorded: by definition, the section keys and the record types their figures include (as the assemblers record them
 * since 0126: executive-pack.ts, executive-dashboard.ts, gate-pack.ts).
 */
const LEGACY_AGGREGATE_SECTIONS: ReadonlyMap<
  string,
  readonly { readonly key: RegExp; readonly types: readonly string[] }[]
> = new Map([
  ["executive_pack", [{ key: /^metrics_/, types: ["benefit", "business_case"] }]],
  [
    "executive_dashboard",
    [
      { key: /^area_value$/, types: ["benefit", "business_case"] },
      { key: /^items_portfolio$/, types: ["benefit"] },
    ],
  ],
  ["gate_pack", [{ key: /^criteria$/, types: ["evidence"] }]],
]);

/**
 * Conservative aggregates of a legacy snapshot: every record of those types MARKED sensitive in its transformation (a
 * superset of what the aggregate included, so a reader who is not admitted to one of them is never told that nothing
 * was restricted). One indexed query (`record_sensitivity_transformation_idx`), and none for other definitions.
 */
async function legacyAggregates(
  db: DbOrTx,
  snapshot: { transformationId: string; content: ReportDocument },
): Promise<AggregateRef[]> {
  const rules = LEGACY_AGGREGATE_SECTIONS.get(snapshot.content.definitionCode) ?? [];
  if (rules.length === 0) return [];
  const marked = await db
    .selectFrom("record_sensitivity")
    .select(["record_type", "record_id"])
    .where("transformation_id", "=", snapshot.transformationId)
    .where("is_sensitive", "=", true)
    .execute();
  if (marked.length === 0) return [];
  const out: AggregateRef[] = [];
  for (const s of snapshot.content.sections)
    for (const rule of rules)
      if (rule.key.test(s.key))
        for (const m of marked)
          if (rule.types.includes(m.record_type))
            out.push({ sectionKey: s.key, recordType: m.record_type, recordId: m.record_id });
  return out;
}

/** The records a stored snapshot's aggregate sections include (report_snapshot_aggregate, or the legacy rule). */
export async function snapshotAggregates(
  db: DbOrTx,
  snapshot: { id: string; transformationId: string; content: ReportDocument },
): Promise<AggregateRef[]> {
  const row = await db
    .selectFrom("report_snapshot")
    .select("aggregates_recorded")
    .where("id", "=", snapshot.id)
    .executeTakeFirst();
  if (row !== undefined && !row.aggregates_recorded) return legacyAggregates(db, snapshot);
  const rows = await db
    .selectFrom("report_snapshot_aggregate")
    .select(["section_key", "record_type", "record_id"])
    .where("snapshot_id", "=", snapshot.id)
    .execute();
  return rows.map((r) => ({ sectionKey: r.section_key, recordType: r.record_type, recordId: r.record_id }));
}

/** A snapshot response (summary members unchanged) with its `content` as this reader may see it. */
export async function snapshotForReader<S extends { id: string; transformationId: string; content: ReportDocument }>(
  db: DbOrTx,
  principal: Principal,
  snapshot: S,
): Promise<S> {
  const content = await documentForReader(db, principal, snapshot.content, await snapshotAggregates(db, snapshot));
  return content === snapshot.content ? snapshot : { ...snapshot, content };
}

/** The references of `items` the reader may see (snapshot source and evidence lists: the restricted row is absent). */
export async function visibleRefs<T>(
  db: DbOrTx,
  principal: Principal,
  items: readonly T[],
  refOf: (item: T) => ReachRef | null,
): Promise<T[]> {
  const pairs = items.map((item) => ({ item, ref: refOf(item) }));
  const restricted = await restrictedRecordRefs(
    db,
    principal,
    pairs.flatMap((p) => (p.ref === null ? [] : [p.ref])),
  );
  if (restricted.size === 0) return [...items];
  return pairs.filter((p) => p.ref === null || !restricted.has(reachKey(p.ref))).map((p) => p.item);
}
