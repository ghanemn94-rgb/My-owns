// T-I4, T-I5, T-I6 (T-DG7-BE-H; ADR-0071 §2, §3; p7-work-split §I.1, §I.4; REQ-S02-003): the in-app requirement register
// through the real server (buildServer, the platform hooks, the access module's policy function) on this run's disposable
// PostgreSQL, for the sessions and the 14 roles.
// The snapshot source is the real file loader (fileRegisterSnapshotSource) behind a delegating wrapper installed with
// vi.mock on `defaultRegisterSnapshotSource` (the transition-decisions-server-wiring precedent), so each test points the
// server at its own snapshot file without editing server.ts. The snapshots are generated by the build's own generator
// (apps/api/scripts/register-snapshot.mjs) from the tree's docs/delivery/requirements.csv, or from a SYNTHETIC fixture
// register for the multi-line row. Read-only routes: nothing is written, nothing is approved, and nothing touches DG0-DG7.
