const state = vi.hoisted(() => ({ source: null as null | SnapshotModule.RegisterSnapshotSource }));
vi.mock("../../../src/modules/release/snapshot.ts", async (importOriginal) => {
  const real = await importOriginal<typeof SnapshotModule>();
  return {
    ...real,
    // The server's source delegates to whichever real file source the current test installed.
    defaultRegisterSnapshotSource: (): SnapshotModule.RegisterSnapshotSource => ({
      load: (log) =>
        state.source === null ? Promise.reject(new real.SnapshotUnavailable("no test source")) : state.source.load(log),
    }),
  };
});
const { fileRegisterSnapshotSource, REGISTER_COLUMNS } = await import("../../../src/modules/release/snapshot.ts");

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Body = any;

const LIST = "/api/v1/admin/requirements";
const ABOUT = "/api/v1/admin/about";
const READERS = ["ADM_TECH", "TO", "KDS", "TD", "AUD"];
const REFUSED = ["SP", "TL", "BO", "WL", "FIN", "CM", "SEC", "ADM_ACCESS", "ADM_METHOD"];
const GENERATOR = fileURLToPath(new URL("../../../scripts/register-snapshot.mjs", import.meta.url));
const TREE_CSV = fileURLToPath(new URL("../../../../../docs/delivery/requirements.csv", import.meta.url));

const work = mkdtempSync(join(process.env["TMPDIR"] ?? tmpdir(), "release-register-"));
let api: TestApi;
const sessions: { role: string; session: Session }[] = [];
const sessionOf = (role: string) => sessions.find((s) => s.role === role)!.session;

/** Runs the build's generator; returns the snapshot path. */
function generate(csv: string, name: string): string {
  const out = join(work, name);
  const r = spawnSync(process.execPath, [GENERATOR, "--csv", csv, "--out", out], { encoding: "utf8" });
  expect(r.status, r.stderr).toBe(0);
  return out;
}
const use = (path: string) => {
  state.source = fileRegisterSnapshotSource(path);
};

let treeSnapshotPath = "";
let tree: { rowCount: number; rows: string[][]; sourceSha256: string };

beforeAll(async () => {
  treeSnapshotPath = generate(TREE_CSV, "tree.json");
  tree = JSON.parse(readFileSync(treeSnapshotPath, "utf8"));
  use(treeSnapshotPath);
  api = await startApi();
  const org = await createOrg(api.db);
  const grantor = await createUser(api.db, org.id);
  for (const { code } of await api.db.selectFrom("role").select("code").orderBy("code").execute()) {
    const u = await createUser(api.db, org.id);
    await grant(api.db, grantor.id, u.id, code, { type: "organization", id: org.id }, org.id);
    sessions.push({ role: code, session: await signIn(api.app, u.subject) });
  }
  const nobody = await createUser(api.db, org.id);
  sessions.push({ role: "(no grant)", session: await signIn(api.app, nobody.subject) });
}, 240_000);

afterAll(async () => {
  await api?.close();
  rmSync(work, { recursive: true, force: true });
}, 60_000);

/** Pages listRequirements to the end; returns every item. */
async function listAll(query: string, limit = 100): Promise<Body[]> {
  const items: Body[] = [];
  let cursor: string | null = null;
  for (let guard = 0; guard < 100; guard += 1) {
    const q: string = [query, `limit=${limit}`, cursor ? `cursor=${encodeURIComponent(cursor)}` : ""]
      .filter(Boolean)
      .join("&");
    const res: { status: number; body: Body } = await call<Body>(api.app, "GET", `${LIST}?${q}`, {
      session: sessionOf("ADM_TECH"),
    });
    expect(res.status, JSON.stringify(res.body)).toBe(200);
    const checked = matchesComponent("RequirementPage", res.body);
    expect(checked.ok, checked.errors).toBe(true);
    items.push(...res.body.items);
    cursor = res.body.nextCursor;
    if (cursor === null) return items;
  }
  throw new Error("pagination did not end");
}

const byId = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const col = (name: string) => REGISTER_COLUMNS.indexOf(name as (typeof REGISTER_COLUMNS)[number]);
const areaOf = (id: string) => /^REQ-([A-Z0-9]+)-/.exec(id)![1]!;

describe("T-I4: listRequirements", () => {
  beforeAll(() => use(treeSnapshotPath));

  it("unfiltered, paged to the end: exactly the snapshot's ids in reqId order; count = rowCount (the A01 clause)", async () => {
    for (const limit of [100, 37]) {
      const items = await listAll("", limit);
      const expected = tree.rows.map((r) => r[0]!).sort(byId);
      expect(items.map((i) => i.reqId)).toEqual(expected);
      expect(items).toHaveLength(tree.rowCount);
      expect(new Set(items.map((i) => i.reqId)).size).toBe(tree.rowCount);
    }
    const first = await call<Body>(api.app, "GET", LIST, { session: sessionOf("ADM_TECH") });
    expect(first.body.items).toHaveLength(25); // the default limit
    expect(first.body.snapshot).toMatchObject({ rowCount: tree.rowCount, sourceSha256: tree.sourceSha256 });
  });

  it("each filter alone and combined returns exactly the matching rows", async () => {
    const expectRows = (pred: (r: string[]) => boolean) =>
      tree.rows
        .filter(pred)
        .map((r) => r[0]!)
        .sort(byId);
    const statuses = [...new Set(tree.rows.map((r) => r[col("status")]!))];
    const cases: [string, (r: string[]) => boolean][] = [
      ["class=SOURCE", (r) => r[col("class")] === "SOURCE"],
      ["class=ENGINEERING", (r) => r[col("class")] === "ENGINEERING"],
      ...statuses.map((s): [string, (r: string[]) => boolean] => [`status=${s}`, (r) => r[col("status")] === s]),
      ["status=BLOCKED", (r) => r[col("status")] === "BLOCKED"],
      ["area=DLV", (r) => areaOf(r[0]!) === "DLV"],
      ["area=S02", (r) => areaOf(r[0]!) === "S02"],
      ["finalGate=DG7", (r) => r[col("final_gate")] === "DG7"],
      [
        "class=USER&status=SPECIFIED&area=S19&finalGate=DG7",
        (r) =>
          r[col("class")] === "USER" &&
          r[col("status")] === "SPECIFIED" &&
          areaOf(r[0]!) === "S19" &&
          r[col("final_gate")] === "DG7",
      ],
      ["area=PB&finalGate=DG7", (r) => areaOf(r[0]!) === "PB" && r[col("final_gate")] === "DG7"],
    ];
    for (const [query, pred] of cases) {
      const items = await listAll(query, 50);
      expect(
        items.map((i) => i.reqId),
        query,
      ).toEqual(expectRows(pred));
    }
    // Summary fields are the register's text verbatim.
    const [one] = await listAll("area=S02", 100);
    const r = tree.rows.find((x) => x[0] === one.reqId)!;
    expect(one).toEqual({
      reqId: r[0],
      class: r[col("class")],
      area: "S02",
      title: r[col("title")],
      sourceRef: r[col("source_ref")],
      finalGate: r[col("final_gate")],
      status: r[col("status")],
      increments: r[col("increments")],
      hasNotes: r[col("notes")] !== "",
    });
  });

  it("a cursor reused with another filter -> 400; limit 0 or 101 -> 400; an unknown parameter or bad enum -> 400", async () => {
    const tech = sessionOf("ADM_TECH");
    const page = await call<Body>(api.app, "GET", `${LIST}?status=IMPLEMENTED&limit=5`, { session: tech });
    expect(page.status).toBe(200);
    const cursor = encodeURIComponent(page.body.nextCursor);
    const reused = await call<Body>(api.app, "GET", `${LIST}?status=SPECIFIED&limit=5&cursor=${cursor}`, {
      session: tech,
    });
    expect(reused.status).toBe(400);
    expect(reused.body.errors[0].code).toBe("validation.cursor");
    const same = await call<Body>(api.app, "GET", `${LIST}?status=IMPLEMENTED&limit=5&cursor=${cursor}`, {
      session: tech,
    });
    expect(same.status).toBe(200);
    for (const q of [
      "limit=0",
      "limit=101",
      "limit=x",
      "unknown=1",
      "class=OTHER",
      "status=DONE",
      "area=S22",
      "finalGate=DG8",
      "cursor=%21%21",
    ]) {
      const res = await call<Body>(api.app, "GET", `${LIST}?${q}`, { session: tech });
      expect(res.status, q).toBe(400);
      expect(res.body.code, q).toBe("validation");
    }
  });
});

describe("T-I5: getRequirement and the role set", () => {
  it("returns every column verbatim for a multi-line row", async () => {
    const values: Record<string, string> = Object.fromEntries(REGISTER_COLUMNS.map((c) => [c, `${c} value`]));
    Object.assign(values, {
      req_id: "REQ-S02-005",
      class: "SOURCE",
      final_gate: "DG7",
      status: "SPECIFIED",
      title: ' Leading space, a comma and "quotes" ',
      procedure: "step one\nstep two, with a comma\n\nstep four",
      notes: 'Missing dependency:\n- "external" item, line two\n',
      evidence: "path/a.md;\npath/b.md",
    });
    const quote = (s: string) => `"${s.replace(/"/g, '""')}"`;
    const csv = join(work, "multiline.csv");
    writeFileSync(
      csv,
      `${REGISTER_COLUMNS.join(",")}\n${REGISTER_COLUMNS.map((c) => quote(values[c]!)).join(",")}\n` +
        `${REGISTER_COLUMNS.map((c) => (c === "req_id" ? "REQ-PB-001" : c === "class" ? "USER" : c === "final_gate" ? "DG1" : c === "status" ? "IMPLEMENTED" : "x")).join(",")}\n`,
    );
    use(generate(csv, "multiline.json"));
    try {
      const res = await call<Body>(api.app, "GET", `${LIST}/REQ-S02-005`, { session: sessionOf("AUD") });
      expect(res.status, JSON.stringify(res.body)).toBe(200);
      const checked = matchesComponent("Requirement", res.body);
      expect(checked.ok, checked.errors).toBe(true);
      const camel = (c: string) => c.replace(/_([a-z])/g, (_, x: string) => x.toUpperCase());
      for (const c of REGISTER_COLUMNS) expect(res.body[c === "req_id" ? "reqId" : camel(c)], c).toBe(values[c]);
      expect(res.body.area).toBe("S02");
      expect(res.body.snapshot.rowCount).toBe(2);
    } finally {
      use(treeSnapshotPath);
    }
  });

  it("an unknown id -> 404; a bad id -> 400; an undeclared query parameter -> 400", async () => {
    const tech = sessionOf("ADM_TECH");
    const unknown = await call<Body>(api.app, "GET", `${LIST}/REQ-S02-999`, { session: tech });
    expect(unknown.status).toBe(404);
    expect(unknown.body.code).toBe("not_found");
    for (const bad of ["REQ-S02-3", "req-s02-003", "REQ-S02-0030", "X"]) {
      const res = await call<Body>(api.app, "GET", `${LIST}/${bad}`, { session: tech });
      expect(res.status, bad).toBe(400);
    }
    const extra = await call<Body>(api.app, "GET", `${LIST}/REQ-S02-003?x=1`, { session: tech });
    expect(extra.status).toBe(400);
    const aboutExtra = await call<Body>(api.app, "GET", `${ABOUT}?x=1`, { session: tech });
    expect(aboutExtra.status).toBe(400);
  });

  it("all three operations: 200 for ADM_TECH, TO, KDS, TD, AUD; 403 for the nine others and no grant; 401 without a session (G1, G2)", async () => {
    expect(sessions.map((s) => s.role)).toEqual(expect.arrayContaining([...READERS, ...REFUSED]));
    expect(sessions).toHaveLength(15); // the 14 roles of the catalogue and a user without a grant
    const known = tree.rows[0]![0]!;
    for (const path of [LIST, `${LIST}/${known}`, ABOUT]) {
      for (const role of READERS) {
        const res = await call<Body>(api.app, "GET", path, { session: sessionOf(role) });
        expect(res.status, `${role} ${path}`).toBe(200);
      }
      for (const role of [...REFUSED, "(no grant)"]) {
        const res = await call<Body>(api.app, "GET", path, { session: sessionOf(role) });
        expect(res.status, `${role} ${path}`).toBe(403);
        expect(res.body.code).toBe("forbidden");
      }
      const anonymous = await call<Body>(api.app, "GET", path);
      expect(anonymous.status, path).toBe(401);
      expect(anonymous.body.code).toBe("unauthenticated");
    }
  });

  it("G5: reads write no audit event", async () => {
    const before = await auditCount(api.db);
    await call<Body>(api.app, "GET", LIST, { session: sessionOf("TO") });
    await call<Body>(api.app, "GET", `${LIST}/${tree.rows[0]![0]!}`, { session: sessionOf("TO") });
    await call<Body>(api.app, "GET", ABOUT, { session: sessionOf("TO") });
    expect(await auditCount(api.db)).toBe(before);
  });
});

describe("T-I6 (G4): a missing or corrupt snapshot", () => {
  it("list and get -> 503 release.register_snapshot_unavailable (never an empty 200); fixed without a restart", async () => {
    const tech = sessionOf("ADM_TECH");
    const path = join(work, "broken.json");
    const good = readFileSync(treeSnapshotPath, "utf8");
    const parsed = JSON.parse(good);
    const known = tree.rows[0]![0]!;
    const broken: [string, string | null][] = [
      ["missing", null],
      ["wrong schemaVersion", JSON.stringify({ ...parsed, schemaVersion: "mth-register-snapshot/2" })],
      ["rowCount != rows", JSON.stringify({ ...parsed, rowCount: parsed.rowCount + 1 })],
      ["not JSON", "{"],
    ];
    for (const [label, content] of broken) {
      rmSync(path, { force: true });
      if (content !== null) writeFileSync(path, content);
      use(path);
      for (const url of [LIST, `${LIST}/${known}`]) {
        const res = await call<Body>(api.app, "GET", url, { session: tech });
        expect(res.status, `${label} ${url}`).toBe(503);
        expect(res.body.code).toBe("release.register_snapshot_unavailable");
        expect(res.body.type).toBe("urn:mth:problem:unavailable");
        expect(res.body.items).toBeUndefined();
        expect(matchesComponent("Problem", res.body).ok).toBe(true);
      }
      // About still answers 200 with null fields.
      const about = await call<Body>(api.app, "GET", ABOUT, { session: tech });
      expect(about.status).toBe(200);
      expect(about.body.register).toBeNull();
      // The same source, the file fixed: the next request succeeds (no restart, the failure was not cached).
      writeFileSync(path, good);
      const fixed = await call<Body>(api.app, "GET", LIST, { session: tech });
      expect(fixed.status, label).toBe(200);
      expect(fixed.body.snapshot.rowCount).toBe(tree.rowCount);
    }
    use(treeSnapshotPath);
  });

  it("authentication and authorization still come first when the snapshot is missing (401, 403 before 503)", async () => {
    use(join(work, "absent.json"));
    try {
      expect((await call<Body>(api.app, "GET", LIST)).status).toBe(401);
      expect((await call<Body>(api.app, "GET", LIST, { session: sessionOf("TL") })).status).toBe(403);
      expect((await call<Body>(api.app, "GET", `${LIST}?limit=0`, { session: sessionOf("TD") })).status).toBe(400);
      expect((await call<Body>(api.app, "GET", LIST, { session: sessionOf("TD") })).status).toBe(503);
    } finally {
      use(treeSnapshotPath);
    }
  });
});
