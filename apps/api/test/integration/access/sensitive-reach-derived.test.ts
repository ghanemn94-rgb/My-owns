// A sensitive benefit in the DERIVED views (T-DG6-BE-Z5; F-DG6-300; ADR-0051 §2 and its 2026-11-04 amendment; D-195
// Q3; REQ-S10-002 "a sensitive benefit is hidden from a workstream member without the grant"; M0188), against the
// run's disposable PostgreSQL. Every value is SYNTHETIC. Marking a record sensitive or granting access is an access
// decision, never a business approval (G1-G6); the G6 instance below is never approved, and nothing here touches
// DG0-DG7.
//
// Ported from the code-security probes zz-cs-r4-sens-title.test.ts and zz-cs-r4-sens-title2.test.ts (round 4), which
// failed on getTraceability, getMissingLinks, the live registers report, the stored snapshot and the G6 readiness.
// Per route, what a reader who is not admitted (TL, AUD, BO2: no grant, not a named party) gets, and why:
//   - traceability graph: the benefit's node and every edge touching it are OMITTED (no count; a rooted query at it is
//     refused as an unknown root); the other nodes' orphan flags stay computed over all edges (truthful);
//   - trace links and allocation set: a link into the benefit is absent; its allocation set is 404;
//   - missing links: the benefit's per-record WARNING is OMITTED (no verdict reads a warning); `benefit_missing` is
//     still decided over every benefit, so it never claims "no benefit";
//   - G6 readiness: a NEUTRAL placeholder ("a restricted benefit ...", no code, title, id or pointer) for EVERY reader,
//     because the item must keep blocking submission (truthful verdict) and its text is frozen into the submission;
//   - change impact preview (sensitive-reach-impact.test.ts, in the change-control world);
//   - live report and stored snapshot (also one generated by an admitted user): the benefit's row is OMITTED; the
//     export stays refused (D-199).
// Positive control: the TO and an explicitly granted TL see the node, the warning, the row and the snapshot row.
import { insertAuditEvent } from "@mth/db";
import { v7 as uuidv7 } from "uuid";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import {
  launchedInitiative,
  pendingBenefit,
  seedClosureWorld,
  type ClosureWorld,
} from "../contract/p4-exercises-be-j.ts";
import { call, seedWorld, startApi, type Res, type Session, type TestApi, type World } from "../../support/harness.ts";
import { ifm } from "../../support/p2-fixtures.ts";

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Body = any;
let api: TestApi;
let w: World;
let c: ClosureWorld;
const TITLE = "Synthetic CONFIDENTIAL BE-Z5 tariff uplift";
const PLANNED = "7654321.1234";
const S = { benefitId: "", code: "", plainId: "", plainCode: "", snapshotByAdmitted: "", snapshotByTl: "" };
const send = (m: string, u: string, o?: Parameters<typeof call>[3]) => call<Body>(api.app, m, u, o);
const ok = (res: Res<Body>, status = 200) => {
  expect(res.status, JSON.stringify(res.body).slice(0, 600)).toBe(status);
  return res.body as Body;
};
const live = () => `${c.b.base}/reports/registers/live?parameters=${encodeURIComponent('{"register":"benefits"}')}`;
/** The rows of a report document that name `recordId`. */
const rowsOf = (doc: Body, recordId: string): Body[] => {
  const found: Body[] = [];
  const walk = (x: Body) => {
    if (x === null || typeof x !== "object") return;
    if (x.recordId === recordId && Array.isArray(x.cells)) found.push(x);
    for (const v of Object.values(x)) walk(v);
  };
  walk(doc);
  return found;
};
const leaks = (body: unknown) => {
  const t = JSON.stringify(body);
  return [TITLE, `${S.code} ${TITLE}`, PLANNED, S.benefitId].filter((n) => t.includes(n));
};

let notAdmitted: [string, Session][];
let admitted: [string, Session][];

beforeAll(async () => {
  api = await startApi();
  w = await seedWorld(api.db);
  c = await seedClosureWorld(api, w);
  const ini = await launchedInitiative(api.db, c.b);
  const sb = await pendingBenefit(api, c, ini);
  const pb = await pendingBenefit(api, c, ini);
  S.benefitId = sb.id;
  S.code = sb.code;
  S.plainId = pb.id;
  S.plainCode = pb.code;
  let cur = ok(await send("GET", `${c.b.base}/benefits/${sb.id}`, { session: c.b.s.bo }));
  ok(
    await send("PATCH", `${c.b.base}/benefits/${sb.id}`, {
      session: c.b.s.bo,
      headers: ifm(cur.version),
      body: { title: TITLE },
    }),
  );
  cur = ok(await send("GET", `${c.b.base}/benefits/${sb.id}`, { session: c.b.s.bo }));
  ok(
    await send("PATCH", `${c.b.base}/benefits/${sb.id}`, {
      session: c.b.s.bo,
      headers: ifm(cur.version),
      body: { plannedValue: PLANNED },
    }),
  );
  // A G6 instance (never approved), as the closure fixture inserts one, so the live readiness can be read.
  const def = await api.db
    .selectFrom("gate_definition")
    .select("default_approver_role_code")
    .where("code", "=", "G6")
    .executeTakeFirstOrThrow();
  const gid = uuidv7();
  await api.db.transaction().execute(async (tx) => {
    await tx
      .insertInto("gate_instance")
      .values({
        id: gid,
        organization_id: c.b.organizationId,
        transformation_id: c.b.transformationId,
        gate_code: "G6",
        approver_role_code: def.default_approver_role_code,
        created_by: c.b.users.tl.id,
        updated_by: c.b.users.tl.id,
      })
      .execute();
    await insertAuditEvent(
      tx,
      { actorType: "user", actorUserId: c.b.users.tl.id, requestId: `be-z5-g6-${gid}`, source: "api" },
      {
        action: "gate_instance.create",
        recordType: "gate_instance",
        recordId: gid,
        organizationId: c.b.organizationId,
        transformationId: c.b.transformationId,
        newVersion: 1,
      },
    );
  });
  ok(
    await send("PUT", `${c.b.base}/records/benefit/${sb.id}/sensitivity`, {
      session: c.s.to.session,
      headers: ifm(0),
      body: { isSensitive: true, reason: "Synthetic commercially sensitive benefit" },
    }),
  );
  // BO2 gets an explicit grant: the admitted reader of the same role as the not-admitted ones (positive control).
  ok(
    await send("POST", "/api/v1/admin/sensitive-grants", {
      session: c.s.to.session,
      body: {
        transformationId: c.b.transformationId,
        recordType: "benefit",
        recordId: sb.id,
        granteeUserId: c.b.users.bo2.id,
        reason: "Synthetic need to know",
      },
    }),
    201,
  );
  notAdmitted = [
    ["TL", c.b.s.tl],
    ["AUD", c.b.s.auditor],
  ];
  admitted = [
    ["TO", c.s.to.session],
    ["BO2 (granted)", c.b.s.bo2],
  ];
  // A snapshot generated by the ADMITTED TO and one generated by the not-admitted TL: both store the benefit's row.
  S.snapshotByAdmitted = ok(
    await send("POST", `${c.b.base}/reports/registers/generate`, {
      session: c.s.to.session,
      body: { parameters: { register: "benefits" } },
    }),
    201,
  ).id;
  const byTl = await send("POST", `${c.b.base}/reports/registers/generate`, {
    session: c.b.s.tl,
    body: { parameters: { register: "benefits" } },
  });
  expect(byTl.status).toBe(201);
  expect(leaks(byTl.body), "the TL's own generate response").toEqual([]);
  S.snapshotByTl = byTl.body.id;
}, 240_000);
afterAll(() => api?.close());

describe("ADR-0051 §2: a sensitive benefit in the derived views (F-DG6-300)", () => {
  it("control: the not-admitted readers get 404 on the benefit; the admitted ones read it", async () => {
    for (const [who, s] of notAdmitted)
      expect((await send("GET", `${c.b.base}/benefits/${S.benefitId}`, { session: s })).status, who).toBe(404);
    for (const [who, s] of admitted)
      expect((await send("GET", `${c.b.base}/benefits/${S.benefitId}`, { session: s })).status, who).toBe(200);
  });

  it("traceability: the node and its edges are omitted for a reader who is not admitted; the admitted see it", async () => {
    for (const [who, s] of notAdmitted) {
      const g = ok(await send("GET", `${c.b.base}/traceability`, { session: s }));
      expect(leaks(g), who).toEqual([]);
      expect(
        g.nodes.some((n: Body) => n.recordId === S.plainId),
        `${who}: the plain benefit stays`,
      ).toBe(true);
      const rooted = await send("GET", `${c.b.base}/traceability?rootType=benefit&rootId=${S.benefitId}`, {
        session: s,
      });
      const unknown = await send("GET", `${c.b.base}/traceability?rootType=benefit&rootId=${uuidv7()}`, {
        session: s,
      });
      expect(rooted.status, who).toBe(unknown.status);
      expect(rooted.body.code, who).toBe(unknown.body.code);
      const links = ok(await send("GET", `${c.b.base}/trace-links?limit=100`, { session: s }));
      expect(leaks(links), `${who}: trace links`).toEqual([]);
      expect(
        (await send("GET", `${c.b.base}/allocation-sets/benefit/${S.benefitId}`, { session: s })).status,
        `${who}: allocation set`,
      ).toBe(404);
    }
    for (const [who, s] of admitted) {
      const g = ok(await send("GET", `${c.b.base}/traceability`, { session: s }));
      const node = g.nodes.find((n: Body) => n.recordId === S.benefitId);
      expect(node?.label, who).toBe(TITLE);
      expect((await send("GET", `${c.b.base}/allocation-sets/benefit/${S.benefitId}`, { session: s })).status).toBe(
        200,
      );
    }
  });

  it("missing links: the benefit's warning is omitted (no count) for a reader who is not admitted", async () => {
    const toItems = ok(await send("GET", `${c.b.base}/missing-links`, { session: c.s.to.session })).items;
    const forBenefit = (items: Body[], id: string) => items.filter((i: Body) => i.recordId === id);
    expect(forBenefit(toItems, S.benefitId).map((i: Body) => i.label)).toEqual([`${S.code} ${TITLE}`]);
    for (const [who, s] of notAdmitted) {
      const m = ok(await send("GET", `${c.b.base}/missing-links`, { session: s }));
      expect(leaks(m), who).toEqual([]);
      expect(forBenefit(m.items, S.benefitId), who).toEqual([]);
      // Nothing else changes: the same items as the TO's, minus the restricted benefit's one.
      expect(m.items.length, who).toBe(toItems.length - 1);
      expect(
        m.items.some((i: Body) => i.code === "benefit_missing"),
        `${who}: never "no benefit"`,
      ).toBe(false);
    }
  });

  it("G6 readiness: a neutral placeholder for every reader; the verdict (count of missing items) is the same", async () => {
    const counts: number[] = [];
    for (const [who, s] of [...notAdmitted, ...admitted]) {
      const r = ok(await send("GET", `${c.b.base}/gates/G6`, { session: s }));
      const text = JSON.stringify(r);
      expect(leaks(r), who).toEqual([]);
      expect(text, who).toContain("Benefits evidence: a restricted benefit has no Finance-validated measurement");
      expect(text, `${who}: the plain benefit is still named`).toContain(`${S.plainCode} `);
      counts.push((text.match(/g6\.benefit_not_validated/g) ?? []).length);
    }
    expect(new Set(counts).size).toBe(1);
  });

  it("live register report and stored snapshots: the row is omitted for a reader who is not admitted", async () => {
    for (const [who, s] of notAdmitted) {
      const r = ok(await send("GET", live(), { session: s }));
      expect(leaks(r), `${who}: live`).toEqual([]);
      expect(rowsOf(r, S.plainId).length, `${who}: the plain row stays`).toBeGreaterThan(0);
      for (const id of [S.snapshotByAdmitted, S.snapshotByTl]) {
        const snap = ok(await send("GET", `${c.b.base}/report-snapshots/${id}`, { session: s }));
        expect(leaks(snap), `${who}: snapshot ${id}`).toEqual([]);
        const sources = ok(await send("GET", `${c.b.base}/report-snapshots/${id}/sources?limit=100`, { session: s }));
        expect(leaks(sources), `${who}: snapshot sources`).toEqual([]);
      }
      const e = await send("POST", "/api/v1/exports", {
        session: s,
        body: { snapshotId: S.snapshotByAdmitted, format: "csv", language: "en" },
        contract: false,
      });
      // D-199 for TL (who may export); AUD holds no export permission and gets the generic 403 first.
      expect(e.status, `${who}: export of the snapshot stays refused (D-199)`).toBe(403);
      expect(e.body.code, who).toBe(who === "AUD" ? "forbidden" : "export.includes_restricted_records");
    }
    for (const [who, s] of admitted) {
      const r = ok(await send("GET", live(), { session: s }));
      // The register row and the benefit's row in the totals tables.
      expect(rowsOf(r, S.benefitId).length, `${who}: live`).toBeGreaterThan(0);
      expect(JSON.stringify(r)).toContain(PLANNED);
      for (const id of [S.snapshotByAdmitted, S.snapshotByTl]) {
        const snap = ok(await send("GET", `${c.b.base}/report-snapshots/${id}`, { session: s }));
        expect(rowsOf(snap, S.benefitId).length, `${who}: snapshot ${id}`).toBeGreaterThan(0);
      }
    }
  });
});
