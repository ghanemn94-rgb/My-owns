const holder = (column: string, names: string, guard: string, kind: InventoryKind = "fk"): InventoryRow => ({
  column,
  kind,
  names,
  operations: [],
  before: "holder already restricted (BE-Y1/Z1/Z4/Z5)",
  status: "holder-restricted",
  fix: guard,
});
const fkChild = (table: string, column: string, owner: string) =>
  holder(
    `${table}.${column}`,
    owner,
    `${table} is a SENSITIVE_CHILD_SOURCES type of its ${owner}: 404 / omitted when the owner is restricted`,
  );
const cannot = (column: string, kind: InventoryKind, names: string): InventoryRow => ({
  column,
  kind,
  names,
  operations: [],
  before: "-",
  status: "cannot-name",
  fix: names,
});
const notServed = (column: string, kind: InventoryKind, names: string): InventoryRow => ({
  column,
  kind,
  names,
  operations: [],
  before: "-",
  status: "not-served",
  fix: "no API response serializes it",
});
const secretRef = (column: string): InventoryRow =>
  cannot(column, "json", "a secret reference (environment or vault key name), never a record id");

