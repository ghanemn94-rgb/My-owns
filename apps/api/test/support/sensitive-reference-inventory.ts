// T-DG6-BE-Z12 (F-DG6-480; D-218, D-219; ADR-0051 §2; REQ-S10-002): the schema-derived inventory of every column that
// can hold the id of a record of the ADR-0051 sensitive set (benefit, business case, evidence) or of a child that
// carries one's values (every SENSITIVE_CHILD_SOURCES table), and what each API response that serializes it does for a
// reader who is not admitted to that record.
//
// The inventory is CHECKED AGAINST THE CATALOG, not against the demo seed
// (`test/integration/access/sensitive-reference-inventory.test.ts`): it must list
//   - every foreign-key column (single or composite) whose referenced column is the `id` of a sensitive or child table;
//   - every uuid column with no foreign key at all (polymorphic `(record_type, record_id)` pairs, scope ids, ...);
//   - every uuid[] column; and every json/jsonb column;
//   - every text column holding an in-app link (link_path, href; T-DG6-BE-Z13) or a key (`key`, `*_key`: idempotency,
//     trigger, event, dedupe and scope keys can be built from record ids; T-DG6-BE-Z13B, D-227) or an error text
//     (`(^|_)error_(message|detail)$`: a job's or a connector's error text can name a record id; T-DG6-BE-Z13C, D-228 (2));
// and nothing that is not in the catalog. A new column of any of these kinds fails the test until it is classified here.
// The sweep (`sensitive-reach-sweep.test.ts`) seeds every row whose `exercise` is "sweep" and checks in the database
// that the column really holds a hidden id before it reads every GET of the contract.
//
// Status:
//   - redacted: every response that serializes the column omits a hidden id, or shows null with
//     `includesRestrictedRecords: true` (or omits the row whose only purpose is to name the record); `fix` names where.
//   - holder-restricted: the row holding the column is itself a sensitive record or a child of one with this column's
//     owner (SENSITIVE_CHILD_SOURCES, or a route guarded by SENSITIVE_REACH_PARAMS): a reader not admitted gets 404 on it
//     and it is omitted from lists, so the id never reaches them.
//   - D-219: excused by D-219 (audit events §2, the grant register §7, the phase-step evidence remove response).
//   - cannot-name: a CHECK constraint, the zod enum or the only writer shows the column never holds a sensitive or child
//     record's id.
//   - not-served: no API response serializes the column.
//   - own-input: served only to the principal who wrote it, as they wrote it (their own draft or saved selection).
//   - open: not repaired; the handback lists it under "What remains". The inventory test logs these. None since
//     T-DG6-BE-Z12B (D-222 decided work_item.subject_id and automation_rule_version.conditions; both are redacted).
// Everything is SYNTHETIC test metadata. Nothing here is a business approval (G1-G6) or touches DG0-DG7.

export type InventoryKind = "fk" | "uuid" | "array" | "json" | "text";
export type InventoryStatus =
  | "redacted"
  | "holder-restricted"
  | "D-219"
  | "cannot-name"
  | "not-served"
  | "own-input"
  | "open";

export interface InventoryRow {
  /** `table.column`. */
  readonly column: string;
  readonly kind: InventoryKind;
  /** What the column can name (a sensitive or child type), or why it cannot. */
  readonly names: string;
  /** The operationIds that serialize the column ([] when none). */
  readonly operations: readonly string[];
  /** The state before T-DG6-BE-Z12. */
  readonly before: string;
  readonly status: InventoryStatus;
  /** Where the redaction is (redacted), the guard (holder-restricted), the citation (D-219) or the reason. */
  readonly fix: string;
  /**
   * For `redacted`: "sweep" (seeded by the sweep and checked in the database), the repository path of the test that
   * seeds it ("<path>#<test name fragment>"), or "PENDING: <reason>" (repaired, no test seeds it yet; listed in the
   * T-DG6-BE-Z12 handback under "What remains" and pinned by the inventory test).
   */
  readonly exercise?: string;
}

