// T-DG6-FE-Z3 round-6 repair (F-DG6-440; ADR-0051 §2 "Totals and rollups" and its 2026-11-06 amendment "the table
// totals and metrics of every report section" are the same for every reader; D-195 Q3; REQ-S10-002) on the REAL stack
// (support/with-stack.sh: the production-initialized stack the full web suite runs on; no mocks), in chromium-en and
// chromium-ar. Ported from the qa-verifier's round-6 probe
// (docs/delivery/test-evidence/DG6/qa/tests/round-6/zz-qa-dg6r6-restricted-label-ui.spec.ts). T-DG6-FE-Z4: like
// p6-report-aggregate-label.spec.ts, the spec creates its own SYNTHETIC users and records instead of using the demo role
// users of `mth-db seed-demo`, which this stack does not have (in the orchestrator's V9 run, dev-login answered 401):
//  - dev.lead creates a transformation (TL there: no grant, not admitted to sensitive records); a SYNTHETIC Benefit
//    Owner adds two financial benefits of different value classes (revenue_uplift, avoided_cost), so the benefits
//    register has one totals section per class with one row each; dev.office (TO, admitted) marks the revenue_uplift
//    benefit sensitive;
//  - through the API, every table section's totals are identical for the TL and the TO, and at least one section has
//    rows for the TO and none for the TL (every row restricted: the case of the finding);
//  - ON SCREEN, live benefits register preview: the TL sees no row of the benefit, the label "Includes restricted
//    records" / "يشمل سجلات مقيدة", and the SAME totals rows as the TO and as before the marking; in the fully
//    restricted section the table keeps its header, a cell with the empty text, and its totals row; the TO sees the
//    row and no label;
//  - the same on the stored snapshot page: a registers snapshot generated by the TO, opened by the TL;
//  - html lang/dir of the language, axe reports 0 serious/critical issues, and the TL's DOM never names the benefit id.
// Before the fix the TL's fully restricted section showed only "No records" and no totals row (the probe's "TL 2
// totals rows, TO 3"). The benefit is unmarked at the end. Marking a record sensitive is an access decision, never a
// business approval (G1-G6); nothing names DG0-DG7. Every value is SYNTHETIC.
//
// Budget (F-DG5-145/146/151; p6-work-split §2 rules 13 and 15): the test sets 240 s. Measured loaded worst case of this
// version: 9.9 s (chromium-en, docs/delivery/handbacks/DG6/T-DG6-FE-Z4-evidence/03-after-restricted-totals.log, while a
// 229-test e2e run used the same machine; 9.5 s in 05-after-e2e-regression-set.log while `pnpm test` ran); 240 s is
// more than 20x that.
import { expect, test, type Locator, type Page } from "@playwright/test";
import { asUser, syntheticUser } from "./support/p3-journey-setup.ts";
import { SYN_RETAIL, apiSession, expectAccessible, langOf, shot, tr, type Lang } from "./support/ui.ts";

const ORG = "01920000-0000-7000-9000-000000000001";

test.describe.configure({ mode: "serial" });
test.setTimeout(240_000);

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Body = any;

async function expectLanguage(page: Page, lang: Lang): Promise<void> {
  await expect(page.locator("html")).toHaveAttribute("lang", lang);
  await expect(page.locator("html")).toHaveAttribute("dir", lang === "ar" ? "rtl" : "ltr");
}

async function preview(page: Page, lang: Lang, tid: string): Promise<Locator> {
  await page.goto(`/transformations/${tid}/reports`);
  const form = page.locator("[data-form='generate-report']");
  await form.locator("#report-definition").selectOption("registers");
  await form.locator("#report-register").selectOption("benefits");
  await form.getByRole("button", { name: tr(lang, "reportsP5.generate.preview") }).click();
  const live = page.locator("[data-live-preview='registers']");
  await expect(live.locator("[data-state='live-not-stored']")).toBeVisible({ timeout: 60_000 });
  await expect(live.locator("[data-report-section]").first()).toBeVisible({ timeout: 60_000 });
  return live;
}

const totalsOf = (scope: Locator) => scope.locator("tr[data-totals='true']").allInnerTexts();

/** The fully restricted section on screen: header, the empty text in a cell spanning the columns, the totals row. */
async function expectTotalsWithoutRows(scope: Locator, lang: Lang, key: string, toTotals: string): Promise<void> {
  const section = scope.locator(`[data-report-section='${key}']`);
  await expect(section.locator(":scope > [data-restricted-records='true']")).toContainText(
    tr(lang, "access.includesRestrictedRecords"),
  );
  const table = section.getByRole("table");
  await expect(table).toHaveCount(1);
  await expect(table.locator("thead th[scope='col']").first()).toBeVisible();
  await expect(table.locator("tr[data-record]")).toHaveCount(0);
  const empty = table.locator(`td[data-empty-table='${key}']`);
  await expect(empty).toHaveText(tr(lang, "reportsP5.noRecords"));
  expect(await empty.getAttribute("colspan")).toBe(String(await table.locator("thead th[scope='col']").count()));
  const totals = table.locator("tfoot tr[data-totals='true']");
  await expect(totals).toHaveCount(1);
  await expect(totals.getByRole("rowheader")).toHaveText(tr(lang, "reportsP5.total"));
  expect(await totals.innerText()).toBe(toTotals);
}

test("F-DG6-440: a report table whose every row is restricted for the reader keeps its totals row (live preview and snapshot)", async ({
  browser,
  playwright,
}, info) => {
  const lang = langOf(info);
  const stamp = Date.now().toString(36);
  const admin = await apiSession(playwright, "dev.admin");
  const tl = await apiSession(playwright, "dev.lead");
  const to = await apiSession(playwright, "dev.office");
  const tid = (
    await tl.call<{ id: string }>("POST", "/api/v1/transformations", {
      businessUnitId: SYN_RETAIL,
      name: `Synthetic FE-Z4 restricted totals ${lang.toUpperCase()} ${stamp}`,
      mode: "end_to_end",
    })
  ).id;
  const T = `/api/v1/transformations/${tid}`;
  const owner = await syntheticUser(
    admin,
    ORG,
    tid,
    `dev.fez4.bo.${lang}.${stamp}`,
    `Synthetic BO FE-Z4 ${lang}`,
    "BO",
    lang,
  );
  const bo = await apiSession(playwright, owner.username);
  const addBenefit = async (title: string, benefitType: string, valueClass: string, line: string) =>
    bo.call<{ id: string; code: string }>("POST", `${T}/benefits`, {
      title,
      description: "Synthetic benefit (T-DG6-FE-Z4 restricted totals).",
      benefitType,
      valueClass,
      ownerUserId: owner.id,
      currency: "SAR",
      financialStatementLine: line,
    });
  // Two value classes: two totals sections of the benefits register, one row each.
  const benefit = await addBenefit(`Synthetic FE-Z4 SECRET ${lang} ${stamp}`, "revenue", "revenue_uplift", "Revenue");
  await addBenefit(`Synthetic FE-Z4 plain ${lang} ${stamp}`, "cost", "avoided_cost", "Opex - network");
  const bid = String(benefit.id);
  const sensPath = `${T}/records/benefit/${bid}/sensitivity`;
  const livePath = `${T}/reports/registers/live?parameters=${encodeURIComponent(JSON.stringify({ register: "benefits" }))}`;

  const toUser = await asUser(browser, lang, "dev.office");
  const tlUser = await asUser(browser, lang, "dev.lead");
  const toPage = toUser.page;
  const tlPage = tlUser.page;
  const tlBefore = await preview(tlPage, lang, tid);
  const beforeTotals = await totalsOf(tlBefore);
  expect(beforeTotals.length, "the benefits register has totals rows").toBeGreaterThan(0);
  expect(await tlBefore.locator(`[data-record='${bid}']`).count(), "TL sees the row before marking").toBeGreaterThan(0);

  const current = await to.call<Body>("GET", sensPath);
  expect(current.isSensitive, "the benefit starts unmarked").toBe(false);
  const mark = await to.call<Body>(
    "PUT",
    sensPath,
    { isSensitive: true, reason: "Synthetic FE-Z3 sensitivity check" },
    { ifMatch: Number(current.version) },
  );
  try {
    // The API: identical totals; the fully restricted sections (rows for the TO, none for the TL).
    const docTo = (await to.call<Body>("GET", livePath)).document;
    const docTl = (await tl.call<Body>("GET", livePath)).document;
    const fullyRestricted: string[] = [];
    for (const s of docTl.sections as Body[]) {
      if (s.kind !== "table") continue;
      const o = (docTo.sections as Body[]).find((x) => x.key === s.key)!;
      expect(s.totals, `API totals of ${s.key}`).toEqual(o.totals);
      expect(
        s.rows.some((r: Body) => r.recordId === bid),
        `API TL row of the benefit in ${s.key}`,
      ).toBe(false);
      if (s.rows.length === 0 && o.rows.length > 0 && s.totals.length > 0) {
        expect(s.includesRestrictedRecords, `API flag of ${s.key}`).toBe(true);
        fullyRestricted.push(String(s.key));
      }
    }
    expect(fullyRestricted.length, "a table section whose every row is restricted for the TL").toBeGreaterThan(0);
    console.log(`FE-Z3 ${lang}: benefit ${bid} (${benefit.code}); fully restricted sections ${fullyRestricted}`);

    // On screen, the live preview.
    const tlLive = await preview(tlPage, lang, tid);
    const toLive = await preview(toPage, lang, tid);
    await expectLanguage(tlPage, lang);
    expect(await tlLive.locator(`[data-record='${bid}']`).count(), "TL: no row of the benefit").toBe(0);
    expect(await toLive.locator(`[data-record='${bid}']`).count(), "TO: the benefit's row").toBeGreaterThan(0);
    await expect(toLive.locator("[data-restricted-records='true']")).toHaveCount(0);
    const tlTotals = await totalsOf(tlLive);
    const toTotals = await totalsOf(toLive);
    console.log(
      `FE-Z3 ${lang} live: TL totals rows ${tlTotals.length}, TO ${toTotals.length}, before ${beforeTotals.length}`,
    );
    expect(tlTotals, "live: the TL's totals rows equal the TO's").toEqual(toTotals);
    expect(tlTotals, "live: the TL's totals rows are unchanged by the marking").toEqual(beforeTotals);
    for (const key of fullyRestricted) {
      const toRow = await toLive.locator(`[data-report-section='${key}'] tr[data-totals='true']`).innerText();
      await expectTotalsWithoutRows(tlLive, lang, key, toRow);
    }
    expect((await tlPage.content()).includes(bid), "TL report DOM names the benefit id").toBe(false);
    await expectAccessible(tlPage, lang, "fez3-tl-live-restricted-totals");
    await tlLive.locator(`[data-report-section='${fullyRestricted[0]}']`).scrollIntoViewIfNeeded();
    await shot(tlPage, lang, "fez3-tl-live-restricted-totals");
    await shot(toPage, lang, "fez3-to-live-restricted-totals");

    // The stored snapshot page: a registers snapshot the TO generates, opened by both.
    const snap = await to.call<{ id: string }>(
      "POST",
      `${T}/reports/registers/generate`,
      { parameters: { register: "benefits", filters: {} } },
      { expect: 201 },
    );
    const snapTotals: Record<string, string[]> = {};
    for (const [who, page] of [
      ["TO", toPage],
      ["TL", tlPage],
    ] as const) {
      await page.goto(`/transformations/${tid}/reports/${snap.id}`);
      const main = page.locator("main#main");
      await expect(main.locator(`[data-report-section='${fullyRestricted[0]}']`)).toBeVisible({ timeout: 60_000 });
      await expectLanguage(page, lang);
      snapTotals[who] = await totalsOf(main);
    }
    expect(snapTotals["TL"], "snapshot: the TL's totals rows equal the TO's").toEqual(snapTotals["TO"]);
    const tlMain = tlPage.locator("main#main");
    for (const key of fullyRestricted) {
      const toRow = await toPage.locator(`main#main [data-report-section='${key}'] tr[data-totals='true']`).innerText();
      await expectTotalsWithoutRows(tlMain, lang, key, toRow);
    }
    expect(await tlMain.locator(`[data-record='${bid}']`).count(), "snapshot: TL sees no row of the benefit").toBe(0);
    expect((await tlPage.content()).includes(bid), "TL snapshot DOM names the benefit id").toBe(false);
    await expectAccessible(tlPage, lang, "fez3-tl-snapshot-restricted-totals");
    await tlMain.locator(`[data-report-section='${fullyRestricted[0]}']`).scrollIntoViewIfNeeded();
    await shot(tlPage, lang, "fez3-tl-snapshot-restricted-totals");
  } finally {
    await to.call(
      "PUT",
      sensPath,
      { isSensitive: false, reason: "Synthetic FE-Z3 cleanup" },
      { ifMatch: Number(mark.version) },
    );
    await toUser.close();
    await tlUser.close();
  }
});
