#!/usr/bin/env node
// The irreversible-migration catalogue (ADR-0068 §3; REQ-S19-013 "the guide identifies each irreversible migration
// and its backup-based recovery"). Every file 0001–last in packages/db/migrations/ gets exactly one entry: id, name,
// sha256, stage, class, irreversible, reasons[], recovery.
//
//   node tools/release/migration-catalogue.mjs [--root <dir>]            write docs/handover/migration-catalogue.json
//                                                                        and the generated table of docs/handover/upgrades.md
//   node tools/release/migration-catalogue.mjs --check [--root <dir>]    exit 1 if either committed output differs
//
// Exit codes (p7-work-split §2 rule 4): 0 PASS, 1 FAIL (--check: the committed output differs), 2 BLOCKED (missing or
// invalid input: a file name, the overrides file, the upgrade guide's markers). No network, no dependency.
//
// Classes (ADR-0068 §3):
//   additive      creates or adds only (tables, columns, indexes, functions, triggers, grants, seed INSERT … VALUES)
//   data_rewrite  changes existing rows (UPDATE, DELETE, INSERT … SELECT, SELECT f(…) FROM t, a data-changing statement
//                 in a DO block), or
//                 replaces an object an EARLIER file created (CREATE OR REPLACE FUNCTION / VIEW / TRIGGER)
//   destructive   DROP …, TRUNCATE, ALTER … TYPE, RENAME, REVOKE (a REVOKE on an object the same file creates is the
//                 hardening of a new object and does not count)
// Irreversible = data_rewrite or destructive. The scanner is heuristic (ADR-0068 Residual 1): it strips comments,
// string literals and the dollar-quoted bodies of functions (so trigger code that contains UPDATE does not count),
// but it DOES scan the body of a DO block, because that code runs at migration time. A top-level `SELECT f(…) FROM t`
// (a function called for each existing row) is a backfill; a top-level `SELECT f(…)` without FROM (for example
// p2_attach_guards) is not classified and stays additive unless an override raises it. An override may raise a class or add a recovery note; it
// never lowers one, and its reason has at least 20 characters.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const MIGRATIONS_DIR = "packages/db/migrations";
export const OVERRIDES = "tools/release/migration-catalogue.overrides.json";
export const OUT_JSON = "docs/handover/migration-catalogue.json";
export const OUT_GUIDE = "docs/handover/upgrades.md";
export const SCHEMA_VERSION = "mth-migration-catalogue/1";
export const OVERRIDES_SCHEMA_VERSION = "mth-migration-catalogue-overrides/1";
export const TABLE_BEGIN = "<!-- migration-catalogue:begin (generated by tools/release/migration-catalogue.mjs; do not edit) -->";
export const TABLE_END = "<!-- migration-catalogue:end -->";
const FILE_PATTERN = /^(\d{4})_[a-z0-9_]+\.sql$/; // = packages/db/src/constants.ts MIGRATION_FILE_PATTERN

export const CLASSES = Object.freeze(["additive", "data_rewrite", "destructive"]);
const RANK = Object.freeze({ additive: 0, data_rewrite: 1, destructive: 2 });

export const RECOVERY_IRREVERSIBLE =
  "Irreversible: restore the pre-upgrade backup set (ADR-0066 §7) into a fresh database and storage, and run the previous release.";
export const RECOVERY_ADDITIVE =
  "Forward-only like every migration: the supported rollback is the restore of the pre-upgrade backup set (ADR-0066 §7) and the previous release.";

export class CatalogueInputError extends Error {}

/**
 * Splits SQL into a "code" text with comments, string literals and function bodies blanked out, and the DO-block
 * bodies (which run at migration time) collected separately. Quoted identifiers stay. Dollar quotes with any tag
 * ($$, $body$) are handled; a dollar body opened right after the keyword DO is a DO block.
 */
export function stripSql(sql) {
  let code = "";
  const doBodies = [];
  let i = 0;
  const n = sql.length;
  while (i < n) {
    const c = sql[i];
    const next = sql[i + 1];
    if (c === "-" && next === "-") {
      const end = sql.indexOf("\n", i);
      i = end === -1 ? n : end;
      code += " ";
      continue;
    }
    if (c === "/" && next === "*") {
      // PostgreSQL block comments nest.
      let depth = 1;
      i += 2;
      while (i < n && depth > 0) {
        if (sql[i] === "/" && sql[i + 1] === "*") (depth += 1), (i += 2);
        else if (sql[i] === "*" && sql[i + 1] === "/") (depth -= 1), (i += 2);
        else i += 1;
      }
      code += " ";
      continue;
    }
    if (c === "'") {
      // E'…' strings allow backslash escapes; '' is a quote inside any string.
      const escapes = i > 0 && /[eE]/.test(sql[i - 1]) && (i < 2 || !/[A-Za-z0-9_]/.test(sql[i - 2]));
      i += 1;
      while (i < n) {
        if (escapes && sql[i] === "\\") i += 2;
        else if (sql[i] === "'" && sql[i + 1] === "'") i += 2;
        else if (sql[i] === "'") break;
        else i += 1;
      }
      i += 1;
      code += "''";
      continue;
    }
    if (c === '"') {
      const end = sql.indexOf('"', i + 1);
      const stop = end === -1 ? n : end + 1;
      code += sql.slice(i, stop);
      i = stop;
      continue;
    }
    if (c === "$" && !(i > 0 && /[A-Za-z0-9_]/.test(sql[i - 1]))) {
      const tag = /^\$([A-Za-z_][A-Za-z0-9_]*)?\$/.exec(sql.slice(i));
      if (tag) {
        const open = tag[0];
        const bodyStart = i + open.length;
        const close = sql.indexOf(open, bodyStart);
        const bodyEnd = close === -1 ? n : close;
        if (/\bDO\s*$/i.test(code)) doBodies.push(sql.slice(bodyStart, bodyEnd));
        code += " $body$ ";
        i = close === -1 ? n : close + open.length;
        continue;
      }
    }
    code += c;
    i += 1;
  }
  return { code, doBodies };
}

const norm = (s) => s.replace(/\s+/g, " ").trim();
const ident = String.raw`(?:"[^"]+"|[A-Za-z_][A-Za-z0-9_$]*)(?:\.(?:"[^"]+"|[A-Za-z_][A-Za-z0-9_$]*))?`;
const bare = (name) => name.replace(/"/g, "").replace(/^public\./i, "").toLowerCase();

/** Objects a statement creates, keyed "function:name", "view:name", "trigger:name", "table:name". */
function createdObjects(stmt) {
  const out = [];
  const fn = new RegExp(String.raw`^CREATE (?:OR REPLACE )?(?:FUNCTION|PROCEDURE) (${ident})`, "i").exec(stmt);
  if (fn) out.push(`function:${bare(fn[1])}`);
  const view = new RegExp(String.raw`^CREATE (?:OR REPLACE )?(?:MATERIALIZED )?VIEW (?:IF NOT EXISTS )?(${ident})`, "i").exec(stmt);
  if (view) out.push(`view:${bare(view[1])}`);
  const trg = new RegExp(String.raw`^CREATE (?:OR REPLACE )?(?:CONSTRAINT )?TRIGGER (${ident}) .*? ON (${ident})`, "i").exec(stmt);
  if (trg) out.push(`trigger:${bare(trg[1])}@${bare(trg[2])}`);
  const table = new RegExp(String.raw`^CREATE (?:UNLOGGED )?TABLE (?:IF NOT EXISTS )?(${ident})`, "i").exec(stmt);
  if (table) out.push(`table:${bare(table[1])}`);
  const seq = new RegExp(String.raw`^CREATE SEQUENCE (?:IF NOT EXISTS )?(${ident})`, "i").exec(stmt);
  if (seq) out.push(`table:${bare(seq[1])}`);
  const type = new RegExp(String.raw`^CREATE (?:TYPE|DOMAIN) (${ident})`, "i").exec(stmt);
  if (type) out.push(`type:${bare(type[1])}`);
  return out;
}

/** The DML of a DO body that runs at migration time (its strings and nested bodies stripped first). */
function scanDoBody(body) {
  const reasons = [];
  const code = norm(stripSql(body).code);
  for (const m of code.matchAll(new RegExp(String.raw`\bUPDATE (?:ONLY )?(${ident}) (?:AS \w+ )?SET\b`, "gi")))
    reasons.push(["data_rewrite", `DO block: UPDATE ${bare(m[1])}`]);
  for (const m of code.matchAll(new RegExp(String.raw`\bDELETE FROM (?:ONLY )?(${ident})`, "gi")))
    reasons.push(["data_rewrite", `DO block: DELETE FROM ${bare(m[1])}`]);
  for (const m of code.matchAll(new RegExp(String.raw`\bINSERT INTO (${ident})[^;]*?\bSELECT\b`, "gi")))
    reasons.push(["data_rewrite", `DO block: INSERT … SELECT into ${bare(m[1])}`]);
  if (/\bEXECUTE\b/i.test(code)) reasons.push(["data_rewrite", "DO block: dynamic SQL (EXECUTE) not scanned"]);
  if (/\bTRUNCATE\b/i.test(code)) reasons.push(["destructive", "DO block: TRUNCATE"]);
  for (const m of code.matchAll(/\bDROP (\w+)/gi)) reasons.push(["destructive", `DO block: DROP ${m[1].toUpperCase()}`]);
  return reasons;
}

/**
 * Classifies one migration. `earlier` is the set of objects created by earlier files (see createdObjects); the
 * objects this file creates are added to it. Returns { class, reasons } with the reasons de-duplicated in order.
 */
export function classifySql(sql, earlier = new Set()) {
  const { code, doBodies } = stripSql(sql);
  const found = [];
  const createdHere = new Set();
  const statements = code
    .split(";")
    .map(norm)
    .filter((s) => s !== "");
  for (const s of statements) for (const o of createdObjects(s)) createdHere.add(o);
  for (const s of statements) {
    const head = s.toUpperCase();
    if (/^UPDATE\b/.test(head)) found.push(["data_rewrite", `UPDATE ${bare(s.split(" ")[1] === "ONLY" ? s.split(" ")[2] : s.split(" ")[1])}`]);
    else if (/^DELETE FROM\b/.test(head)) found.push(["data_rewrite", `DELETE FROM ${bare(s.split(" ")[2])}`]);
    else if (/^INSERT INTO\b/.test(head) && /\bSELECT\b/.test(head))
      found.push(["data_rewrite", `INSERT … SELECT into ${bare(s.split(" ")[2].replace(/\(.*$/, ""))}`]);
    else if (/^WITH\b/.test(head) && /\b(UPDATE|DELETE|INSERT)\b/.test(head))
      found.push(["data_rewrite", "WITH … data-changing statement"]);
    else {
      // A function called once per existing row (`SELECT f(x.id, …) FROM transformation x`) is a backfill.
      const backfill = new RegExp(String.raw`^SELECT (${ident}) ?\(.*\) FROM (${ident})`, "i").exec(s);
      if (backfill) found.push(["data_rewrite", `backfill: ${bare(backfill[1])}(…) for each row of ${bare(backfill[2])}`]);
    }
    if (/^TRUNCATE\b/.test(head)) found.push(["destructive", "TRUNCATE"]);
    if (/^REVOKE\b/.test(head)) {
      const on = new RegExp(
        String.raw`\bON (?:(TABLE|FUNCTION|PROCEDURE|SEQUENCE|SCHEMA|ALL TABLES IN SCHEMA|ALL FUNCTIONS IN SCHEMA|ALL SEQUENCES IN SCHEMA) )?(${ident})`,
        "i",
      ).exec(s);
      const kind = (on?.[1] ?? "TABLE").toUpperCase();
      const key = `${kind === "FUNCTION" || kind === "PROCEDURE" ? "function" : "table"}:${on ? bare(on[2]) : ""}`;
      if (!on || !createdHere.has(key))
        found.push(["destructive", `REVOKE${on ? ` on ${on[1] ? `${on[1].toLowerCase()} ` : ""}${bare(on[2])}` : ""}`]);
    }
    for (const m of head.matchAll(/\bDROP (\w+)(?: (\w+))?/g)) {
      const what = m[1] === "NOT" && m[2] === "NULL" ? "NOT NULL" : m[1];
      found.push(["destructive", `DROP ${what}`]);
    }
    if (/\bRENAME\b/.test(head)) found.push(["destructive", "RENAME"]);
    if (new RegExp(String.raw`\bALTER (?:COLUMN )?${ident} (?:SET DATA )?TYPE\b`, "i").test(s))
      found.push(["destructive", "ALTER … TYPE"]);
    if (/^CREATE OR REPLACE\b/.test(head))
      for (const o of createdObjects(s)) if (earlier.has(o)) found.push(["data_rewrite", `replaces ${o.replace(":", " ")}`]);
  }
  for (const body of doBodies) found.push(...scanDoBody(body));
  for (const o of createdHere) earlier.add(o);
  let cls = "additive";
  const reasons = [];
  for (const [c, r] of found) {
    if (RANK[c] > RANK[cls]) cls = c;
    if (!reasons.includes(r)) reasons.push(r);
  }
  return { class: cls, reasons };
}

/** Validates the overrides file; returns a Map id → override. Throws CatalogueInputError naming the problem. */
export function parseOverrides(text, knownIds) {
  let doc;
  try {
    doc = JSON.parse(text);
  } catch (e) {
    throw new CatalogueInputError(`${OVERRIDES}: not valid JSON (${e.message})`);
  }
  if (doc?.schemaVersion !== OVERRIDES_SCHEMA_VERSION || !Array.isArray(doc.overrides))
    throw new CatalogueInputError(`${OVERRIDES}: expected schemaVersion '${OVERRIDES_SCHEMA_VERSION}' and an overrides array`);
  const out = new Map();
  for (const o of doc.overrides) {
    const id = o?.id;
    if (typeof id !== "string" || !/^\d{4}$/.test(id)) throw new CatalogueInputError(`${OVERRIDES}: an override has no 4-digit id`);
    if (out.has(id)) throw new CatalogueInputError(`${OVERRIDES}: two overrides for ${id}`);
    if (!knownIds.has(id)) throw new CatalogueInputError(`${OVERRIDES}: override ${id} names no migration file (stale)`);
    if (!CLASSES.includes(o.class)) throw new CatalogueInputError(`${OVERRIDES}: override ${id} has an unknown class '${o.class}'`);
    if (typeof o.reason !== "string" || o.reason.trim().length < 20)
      throw new CatalogueInputError(`${OVERRIDES}: override ${id} needs a reason of at least 20 characters`);
    if (o.recoveryNote !== undefined && (typeof o.recoveryNote !== "string" || o.recoveryNote.trim() === ""))
      throw new CatalogueInputError(`${OVERRIDES}: override ${id} has an empty recoveryNote`);
    const extra = Object.keys(o).filter((k) => !["id", "class", "reason", "recoveryNote"].includes(k));
    if (extra.length > 0) throw new CatalogueInputError(`${OVERRIDES}: override ${id} has unknown key(s) ${extra.join(", ")}`);
    out.set(id, o);
  }
  return out;
}

/** Builds the catalogue document from the migration files under `root`. */
export function buildCatalogue(root = REPO) {
  const dir = join(root, MIGRATIONS_DIR);
  if (!existsSync(dir)) throw new CatalogueInputError(`${MIGRATIONS_DIR}: not found`);
  const names = readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const files = names.map((name) => {
    const m = FILE_PATTERN.exec(name);
    if (!m) throw new CatalogueInputError(`${MIGRATIONS_DIR}/${name}: name does not match NNNN_snake_case.sql`);
    return { id: m[1], name, bytes: readFileSync(join(dir, name)) };
  });
  for (let k = 1; k < files.length; k++)
    if (files[k].id <= files[k - 1].id) throw new CatalogueInputError(`${MIGRATIONS_DIR}: duplicate id ${files[k].id}`);
  const overridesPath = join(root, OVERRIDES);
  const overrides = existsSync(overridesPath)
    ? parseOverrides(readFileSync(overridesPath, "utf8"), new Set(files.map((f) => f.id)))
    : new Map();
  const earlier = new Set();
  const entries = files.map((f) => {
    const scanned = classifySql(f.bytes.toString("utf8"), earlier);
    const o = overrides.get(f.id);
    if (o && RANK[o.class] < RANK[scanned.class])
      throw new CatalogueInputError(
        `${OVERRIDES}: override ${f.id} would lower the class from ${scanned.class} to ${o.class}; overrides only raise`,
      );
    const cls = o ? o.class : scanned.class;
    const reasons = [...scanned.reasons];
    if (o) reasons.push(`override: ${o.reason.trim()}`);
    const irreversible = cls !== "additive";
    const recovery = `${irreversible ? RECOVERY_IRREVERSIBLE : RECOVERY_ADDITIVE}${o?.recoveryNote ? ` ${o.recoveryNote.trim()}` : ""}`;
    const stage = /^\d{4}_(p\d+)_/.exec(f.name)?.[1] ?? "p1";
    return {
      id: f.id,
      name: f.name,
      sha256: createHash("sha256").update(f.bytes).digest("hex"),
      stage,
      class: cls,
      irreversible,
      reasons,
      recovery,
    };
  });
  return {
    schemaVersion: SCHEMA_VERSION,
    generatedBy: "tools/release/migration-catalogue.mjs",
    migrationsDir: MIGRATIONS_DIR,
    count: entries.length,
    counts: Object.fromEntries(CLASSES.map((c) => [c, entries.filter((e) => e.class === c).length])),
    entries,
  };
}

export const renderJson = (catalogue) => `${JSON.stringify(catalogue, null, 2)}\n`;

const cell = (s) => s.replace(/\|/g, "\\|");

/** The Markdown table between the guide's markers (irreversible rows first, then every additive id in one line). */
export function renderTable(catalogue) {
  const lines = [
    TABLE_BEGIN,
    "",
    `${catalogue.count} migrations: ${catalogue.counts.additive} additive, ${catalogue.counts.data_rewrite} data_rewrite, ${catalogue.counts.destructive} destructive.`,
    "",
    "| Id | Migration | Stage | Class | Why (scanner and overrides) | Recovery |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const e of catalogue.entries.filter((x) => x.irreversible))
    lines.push(`| ${e.id} | \`${e.name}\` | ${e.stage} | ${e.class} | ${cell(e.reasons.join("; "))} | ${cell(e.recovery)} |`);
  lines.push(
    "",
    `Additive (${catalogue.counts.additive}): ${catalogue.entries
      .filter((x) => !x.irreversible)
      .map((x) => x.id)
      .join(", ")}. Recovery for each: ${RECOVERY_ADDITIVE}`,
    "",
    TABLE_END,
  );
  return lines.join("\n");
}

/** Replaces the generated block of the guide's text; throws when the markers are missing or out of order. */
export function spliceGuide(guide, table) {
  const a = guide.indexOf(TABLE_BEGIN);
  const b = guide.indexOf(TABLE_END);
  if (a === -1 || b === -1 || b < a) throw new CatalogueInputError(`${OUT_GUIDE}: the generated-table markers are missing`);
  return guide.slice(0, a) + table + guide.slice(b + TABLE_END.length);
}

function main(argv) {
  const check = argv.includes("--check");
  const r = argv.indexOf("--root");
  const root = r === -1 ? REPO : resolve(argv[r + 1] ?? "");
  const unknown = argv.filter((a, k) => a !== "--check" && a !== "--root" && !(r !== -1 && k === r + 1));
  if (unknown.length > 0 || (r !== -1 && argv[r + 1] === undefined)) {
    console.error("BLOCKED: usage: node tools/release/migration-catalogue.mjs [--check] [--root <dir>]");
    return 2;
  }
  let catalogue;
  let guide;
  try {
    catalogue = buildCatalogue(root);
    const guidePath = join(root, OUT_GUIDE);
    if (!existsSync(guidePath)) throw new CatalogueInputError(`${OUT_GUIDE}: not found`);
    guide = spliceGuide(readFileSync(guidePath, "utf8"), renderTable(catalogue));
  } catch (e) {
    if (e instanceof CatalogueInputError) {
      console.error(`BLOCKED: ${e.message}`);
      return 2;
    }
    throw e;
  }
  const json = renderJson(catalogue);
  const summary = `${catalogue.count} migrations (${catalogue.counts.additive} additive, ${catalogue.counts.data_rewrite} data_rewrite, ${catalogue.counts.destructive} destructive)`;
  if (check) {
    const stale = [];
    const jsonPath = join(root, OUT_JSON);
    if (!existsSync(jsonPath) || readFileSync(jsonPath, "utf8") !== json) stale.push(OUT_JSON);
    if (readFileSync(join(root, OUT_GUIDE), "utf8") !== guide) stale.push(OUT_GUIDE);
    if (stale.length > 0) {
      console.error(`FAIL: migration catalogue: ${stale.join(" and ")} differ(s) from a fresh generation; run node tools/release/migration-catalogue.mjs`);
      return 1;
    }
    console.log(`PASS: migration catalogue up to date: ${summary}`);
    return 0;
  }
  writeFileSync(join(root, OUT_JSON), json);
  writeFileSync(join(root, OUT_GUIDE), guide);
  console.log(`migration catalogue written: ${summary}`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exitCode = main(process.argv.slice(2));
