#!/usr/bin/env node
// deploy/scripts/drill/fake-idp-server.mjs: the SYNTHETIC drill IdP of the transfer drill (ADR-0069 §4; p7-work-split
// §B.2; T-DG7-DO-D). DRILL-ONLY: it is never part of the runtime tree and stands in for no corporate IdP.
//
//   node deploy/scripts/drill/fake-idp-server.mjs --port <p> --users <users.json> --client-secret-file <file>
//        --redirect-uri <uri> [--redirect-uri <uri> ...]
//
// It starts the P6 fake OpenID Provider (apps/api/test/support/fake-idp.ts: discovery, JWKS, the PKCE token endpoint,
// RS256 ID tokens, validated by the real openid-client) on 127.0.0.1:<p>, with:
//   - the client secret read from <file> (a synthetic value the drill generates; the fake's built-in test secret is
//     replaced, so no repository value is a credential of the drill);
//   - an authorization endpoint that the fake lacks: the user agent names the user with `login_hint=<sub>` (the drill's
//     stand-in for typing a password), the redirect_uri must be one of --redirect-uri (the client registration, ADR-0069
//     §1 item 5), and the answer is a 302 to the redirect URI with the code and state;
//   - <users.json>: [{ "sub", "email"?, "email_verified"?, "name"? }], every user synthetic.
// On start it prints ONE JSON line: { issuer, clientId, label, users: [{ sub }] }. It stops on SIGTERM or SIGINT.
// Exit codes: 0 stopped, 2 BLOCKED (usage or unreadable input), 3 BLOCKED (the fake cannot be loaded or the port bound).
import { readFileSync } from "node:fs";
import { createServer } from "node:http";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

export const DRILL_IDP_LABEL = "synthetic drill IdP (not a corporate IdP)";
const FAKE = new URL("../../../apps/api/test/support/fake-idp.ts", import.meta.url);

/**
 * Starts the drill IdP. Returns { idp, issuer, clientId, stop() }. `users` maps a subject to its claims; `redirectUris`
 * is the registered set. Exported for the drill's own tests.
 */
export async function startDrillIdp({ port, users, clientSecret, redirectUris }) {
  const { FakeIdp } = await import(FAKE.href);
  const idp = new FakeIdp();
  idp.clientSecret = clientSecret; // synthetic, generated by the drill (never the fake's built-in test value)
  const original = idp.handle.bind(idp);
  const authPath = "/realms/mth-test/protocol/openid-connect/auth";
  idp.handle = async (req, res) => {
    const url = new URL(req.url ?? "/", "http://127.0.0.1");
    if (url.pathname !== authPath) return original(req, res);
    const sub = url.searchParams.get("login_hint") ?? "";
    const redirect = url.searchParams.get("redirect_uri") ?? "";
    const send = (status, body) => {
      res.writeHead(status, { "content-type": "application/json" });
      res.end(JSON.stringify(body));
    };
    if (url.searchParams.get("client_id") !== idp.clientId) return send(400, { error: "unauthorized_client" });
    if (!redirectUris.includes(redirect)) return send(400, { error: "invalid_redirect_uri" });
    const claims = users.get(sub);
    if (!claims) return send(401, { error: "access_denied", error_description: "unknown synthetic user" });
    const { code, state } = idp.issueCode(`${idp.issuer.replace(/\/realms\/.*$/, "")}${req.url}`, claims);
    const back = new URL(redirect);
    back.searchParams.set("code", code);
    back.searchParams.set("state", state);
    res.writeHead(302, { location: back.toString() });
    res.end();
  };
  // FakeIdp.start() listens on an ephemeral port; the drill takes its port from the pool (p7-work-split §2 rule 2).
  idp.server = createServer((req, res) => void idp.handle(req, res));
  await new Promise((resolve, reject) => {
    idp.server.once("error", reject);
    idp.server.listen(port, "127.0.0.1", resolve);
  });
  const actual = idp.server.address().port;
  idp.origin = `http://127.0.0.1:${actual}`;
  idp.issuer = idp.issuerOf("mth-test");
  idp.otherIssuer = idp.issuerOf("mth-other");
  return {
    idp,
    issuer: idp.issuer,
    clientId: idp.clientId,
    port: actual,
    stop: () => new Promise((resolve) => idp.server.close(() => resolve())),
  };
}

/** Reads <users.json> into a Map sub -> claims. */
export function readUsers(text) {
  const list = JSON.parse(text);
  if (!Array.isArray(list) || list.length === 0) throw new Error("users file must be a non-empty array");
  const m = new Map();
  for (const u of list) {
    if (typeof u?.sub !== "string" || u.sub.length === 0) throw new Error("every user needs a sub");
    m.set(u.sub, {
      sub: u.sub,
      ...(u.email ? { email: u.email, email_verified: u.email_verified ?? true } : {}),
      ...(u.name ? { name: u.name } : {}),
    });
  }
  return m;
}

async function main() {
  let v;
  try {
    ({ values: v } = parseArgs({
      args: process.argv.slice(2),
      options: {
        port: { type: "string" },
        users: { type: "string" },
        "client-secret-file": { type: "string" },
        "redirect-uri": { type: "string", multiple: true },
      },
      strict: true,
    }));
  } catch {
    v = {};
  }
  if (!/^\d+$/.test(v.port ?? "") || !v.users || !v["client-secret-file"] || !(v["redirect-uri"]?.length > 0)) {
    console.error(
      "BLOCKED: usage: fake-idp-server.mjs --port <p> --users <file> --client-secret-file <file> --redirect-uri <uri>...",
    );
    process.exit(2);
  }
  let users, secret;
  try {
    users = readUsers(readFileSync(v.users, "utf8"));
    secret = readFileSync(v["client-secret-file"], "utf8").trim();
    if (secret.length < 16) throw new Error("the client secret file holds fewer than 16 characters");
  } catch (e) {
    console.error(`BLOCKED: fake-idp-server: ${e.message}`);
    process.exit(2);
  }
  let s;
  try {
    s = await startDrillIdp({ port: Number(v.port), users, clientSecret: secret, redirectUris: v["redirect-uri"] });
  } catch (e) {
    console.error(`BLOCKED: fake-idp-server: cannot start: ${e.code ?? e.message}`);
    process.exit(3);
  }
  console.log(
    JSON.stringify({
      issuer: s.issuer,
      clientId: s.clientId,
      label: DRILL_IDP_LABEL,
      users: [...users.keys()].map((sub) => ({ sub })),
    }),
  );
  const stop = () => s.stop().then(() => process.exit(0));
  process.on("SIGTERM", stop);
  process.on("SIGINT", stop);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) await main();
